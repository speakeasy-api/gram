type toolExposureReceipt struct {
	Outcome      string   `json:"outcome"`
	Applied      []string `json:"applied"`
	Unchanged    []string `json:"unchanged"`
	VersionAfter int64    `json:"version_after"`
	Publication  string   `json:"publication_request"`
}

type toolExposureMutationRequest struct {
	Operation       string   `json:"operation"`
	ProjectID       string   `json:"project_id"`
	MCPID           string   `json:"mcp_id"`
	ToolURNs        []string `json:"tool_urns"`
	ExpectedVersion string   `json:"expected_version"`
}

func (s *MCPToolExposureService) change(ctx context.Context, principal Principal, operation string, input ChangeMCPToolsInput) (MCPToolExposureMutationOutput, error) {
	if !s.valid() {
		return MCPToolExposureMutationOutput{}, toolExposureUnavailable(errors.New("tool exposure service is not composed"))
	}
	projectID, mcpID, requested, err := s.validate(input)
	if err != nil {
		return MCPToolExposureMutationOutput{}, err
	}
	project, err := s.resolveTarget(ctx, principal, projectID, mcpID)
	if err != nil {
		return MCPToolExposureMutationOutput{}, err
	}
	// The fresh target read, the version check and the tool-name check all
	// happen inside the receipt transaction. Doing any of them here would
	// defeat replay: a retry of a change that already committed would report a
	// conflict against the list it itself moved, or not_found once the target
	// was deleted or unlinked afterwards, instead of returning the stored
	// result the idempotency key promises.
	normalized := toolExposureMutationRequest{
		Operation: operation, ProjectID: project.ID.String(), MCPID: mcpID.String(),
		ToolURNs: toolURNStrings(requested), ExpectedVersion: input.ExpectedVersion,
	}
	payload, err := json.Marshal(normalized)
	if err != nil {
		return MCPToolExposureMutationOutput{}, toolExposureInvalid("The tool exposure change could not be normalized.")
	}
	digest := sha256.Sum256(append([]byte("platform-mcp-tool-exposure-v1\x00"+operation+"\x00"), payload...))

	var toolsetID uuid.UUID
	receipt, err := executeMutationReceipt(ctx, mutationReceiptExecution[toolExposureReceipt]{
		DB: s.db, Now: s.now, Principal: principal, Project: project, Operation: operation,
		IdempotencyKey: input.IdempotencyKey, InputHash: hex.EncodeToString(digest[:]), Label: "MCP tool exposure",
		Invalid: func(error) error { return toolExposureInvalid("The tool exposure request is invalid.") },
		Conflict: func(message string) error {
			return &MCPToolExposureError{Code: "conflict", Message: message, Cause: ErrMCPToolExposureConflict}
		},
		Unavailable: toolExposureUnavailable,
		ValidateReplay: func(stored []byte) bool {
			var result toolExposureReceipt
			return json.Unmarshal(stored, &result) == nil && (result.Outcome == "applied" || result.Outcome == "no_op")
		},
		EncodeResult: func(result toolExposureReceipt) ([]byte, error) {
			encoded, err := json.Marshal(result)
			if err != nil {
				return nil, fmt.Errorf("encode tool exposure receipt: %w", err)
			}
			return encoded, nil
		},
		Mutate: func(ctx context.Context, tx pgx.Tx) (toolExposureReceipt, error) {
			// Re-read the exposure through the transaction. The toolsets helper
			// then takes the toolset row lock and recomputes the list from the
			// committed one, so a concurrent writer cannot be overwritten.
			row, err := s.exposureRow(ctx, s.queries.WithTx(tx), principal, project.ID, mcpID)
			if err != nil {
				return toolExposureReceipt{}, s.classifyTargetError(err)
			}
			locked := toolExposureFromRow(project.ID, mcpID, row)
			if !hmac.Equal([]byte(locked.ExposureVersion), []byte(input.ExpectedVersion)) {
				return toolExposureReceipt{}, toolExposureConflict()
			}
			// Under the same lock that performs the write, so the set of
			// servers this change moves cannot grow between the check and the
			// write.
			if err := s.authorizeEveryAffectedServer(ctx, project.ID, mcpID, row.FrontingServerIds); err != nil {
				return toolExposureReceipt{}, err
			}
			toolsetID = row.ToolsetID
			// Both halves refuse a name they cannot act on rather than
			// reporting it as unchanged. A tool the server already exposes is
			// still removable after its definition is gone, so a name already
			// on the server counts as known.
			if err := s.requireKnownTools(ctx, s.queries.WithTx(tx), principal, project.ID, requested, row.ToolUrns); err != nil {
				return toolExposureReceipt{}, err
			}
			change := toolsets.ToolExposureChange{Add: requested}
			if operation == operationRemoveMCPTools {
				change = toolsets.ToolExposureChange{Remove: requested}
			}
			actor := &contextvalues.AuthContext{ActiveOrganizationID: principal.OrganizationID, UserID: principal.UserID, ProjectID: &project.ID}
			applied, err := toolsets.ChangeToolsetToolsInTransaction(ctx, tx, s.logger, s.audit, actor, toolsetID, row.ToolsetVersion, change)
			if err != nil {
				return toolExposureReceipt{}, classifyToolExposureError(err)
			}
			result := toolExposureReceipt{
				Outcome: "no_op", Applied: toolURNStrings(applied.Applied), Unchanged: toolURNStrings(applied.Unchanged),
				VersionAfter: applied.VersionAfter, Publication: string(plugins.ProjectPublicationNotConfigured),
			}
			if !applied.Changed {
				return result, nil
			}
			result.Outcome = "applied"
			outcome, err := s.publication.ProjectWithOutcome(ctx, tx, principal.OrganizationID, project.ID, principal.UserID)
			if err != nil {
				return toolExposureReceipt{}, fmt.Errorf("request MCP tool exposure publication: %w", err)
			}
			result.Publication = string(outcome)
			return result, nil
		},
	})
	if err != nil {
		return MCPToolExposureMutationOutput{}, err
	}
	var stored toolExposureReceipt
	if err := json.Unmarshal(receipt.ResultPayload, &stored); err != nil {
		return MCPToolExposureMutationOutput{}, toolExposureUnavailable(err)
	}
	return s.finish(ctx, principal, project, mcpID, stored, receipt), nil
}

func (s *MCPToolExposureService) finish(ctx context.Context, principal Principal, project ResolvedProject, mcpID uuid.UUID, stored toolExposureReceipt, receipt OperationReceipt) MCPToolExposureMutationOutput {
	output := MCPToolExposureMutationOutput{
		Outcome: stored.Outcome, Applied: stored.Applied, Unchanged: stored.Unchanged,
		Distributions: []MCPDistribution{}, PublicationRequest: stored.Publication, PublishSignal: "not_requested",
		Receipt: riskMutationToolReceipt(receipt),
	}
	if output.Applied == nil {
		output.Applied = []string{}
	}
	if output.Unchanged == nil {
		output.Unchanged = []string{}
	}
	if stored.Outcome == "applied" && stored.Publication != string(plugins.ProjectPublicationEnqueued) {
		if s.publisher == nil {
			output.PublishSignal = "unavailable"
		} else if err := plugins.SignalPluginPublishAfterRequest(ctx, s.publisher, plugins.ProjectPublicationRequestOutcome(stored.Publication), project.ID, principal.UserID); err != nil {
			output.PublishSignal = "request_failed"
		} else {
			output.PublishSignal = "best_effort_requested"
		}
	}
	if memberships, err := s.queries.ListPlatformMCPInventoryPluginMemberships(ctx, platformrepo.ListPlatformMCPInventoryPluginMembershipsParams{
		OrganizationID: principal.OrganizationID,
		ProjectID:      uuid.NullUUID{UUID: project.ID, Valid: true},
		McpServerIds:   []uuid.UUID{mcpID},
	}); err == nil {
		if distributions, ok := inventoryDistributions(memberships)[mcpID]; ok {
			output.Distributions = distributions
		}
	}
	exposure, err := s.Exposure(ctx, principal, project.ID, mcpID)
	if err != nil {
		output.SnapshotScope = "verification_unavailable"
		return output
	}
	output.Exposure = &exposure
	output.SnapshotScope = "fresh_read_after_commit"
	return output
}

func (s *MCPToolExposureService) validate(input ChangeMCPToolsInput) (uuid.UUID, uuid.UUID, []urn.Tool, error) {
	if !input.Confirmed {
		return uuid.Nil, uuid.Nil, nil, toolExposureInvalid("Confirm the exact project, MCP server, and tool list with the user before changing which tools the server exposes.")
	}
	key := strings.TrimSpace(input.IdempotencyKey)
	if key == "" || len(key) > 128 {
		return uuid.Nil, uuid.Nil, nil, toolExposureInvalid("Provide a stable idempotency key so retrying this exact change is safe.")
	}
	if len(strings.TrimSpace(input.ExpectedVersion)) != sha256.Size*2 {
		return uuid.Nil, uuid.Nil, nil, toolExposureInvalid("Provide the exposure version from the latest read of this MCP server.")
	}
	projectID, err := uuid.Parse(strings.TrimSpace(input.ProjectID))
	if err != nil {
		return uuid.Nil, uuid.Nil, nil, toolExposureInvalid("Provide an explicit project ID.")
	}
	mcpID, err := uuid.Parse(strings.TrimSpace(input.MCPID))
	if err != nil {
		return uuid.Nil, uuid.Nil, nil, toolExposureInvalid("Provide the exact MCP server ID.")
	}
	if len(input.ToolURNs) == 0 {
		return uuid.Nil, uuid.Nil, nil, toolExposureInvalid("Name at least one tool.")
	}
	if len(input.ToolURNs) > maxToolExposureBatch {
		return uuid.Nil, uuid.Nil, nil, toolExposureInvalid(fmt.Sprintf("Name at most %d tools in one change.", maxToolExposureBatch))
	}
	seen := make(map[string]bool, len(input.ToolURNs))
	requested := make([]urn.Tool, 0, len(input.ToolURNs))
	var malformed []string
	for _, value := range input.ToolURNs {
		trimmed := strings.TrimSpace(value)
		parsed, err := urn.ParseTool(trimmed)
		if err != nil {
			malformed = append(malformed, trimmed)
			continue
		}
		if seen[parsed.String()] {
			continue
		}
		seen[parsed.String()] = true
		requested = append(requested, parsed)
	}
	if len(malformed) > 0 {
		return uuid.Nil, uuid.Nil, nil, &MCPToolExposureError{
			Code: "invalid_request", UnknownTools: malformed, Cause: ErrMCPToolExposureInvalid,
			Message: "Some of the named tools are not tool identifiers. Use the exact tool URNs from the project's tool list.",
		}
	}
	return projectID, mcpID, requested, nil
}

// resolveTarget authorizes before it looks anything up. Resolving the named
// project first would let an organization administrator without mcp:write tell
// a real project from an invented one by comparing not_found against a
// permission denial, which is a project-id oracle.
func (s *MCPToolExposureService) resolveTarget(ctx context.Context, principal Principal, projectID, mcpID uuid.UUID) (ResolvedProject, error) {
	if principal.OrganizationID == "" || principal.UserID == "" {
		return ResolvedProject{}, toolExposureInvalid("The tool exposure request is missing its caller identity.")
	}
	if err := s.admin.RequireLiveOrgAdmin(ctx, principal); err != nil {
		return ResolvedProject{}, toolExposureAdminAuthorizationError(err)
	}
	// Checked against the ids the caller named, before anything confirms they
	// exist, so the answer is the same for a real and an invented target.
	if err := s.engine.Require(ctx, authz.MCPCheck(authz.ScopeMCPWrite, mcpID.String(), projectID.String())); err != nil {
		mapped := toolExposureAuthorizationError(err, authz.ScopeMCPWrite)
		if _, ok := errors.AsType[*ExternalAuthorizationError](mapped); !ok {
			// Same reasoning as the admin check: only a denial is safe to
			// report verbatim, and anything else is an evaluation failure.
			return ResolvedProject{}, toolExposureUnavailable(err)
		}
		return ResolvedProject{}, mapped
	}
	project, err := s.queries.ResolvePlatformMCPProjectByID(ctx, platformrepo.ResolvePlatformMCPProjectByIDParams{OrganizationID: principal.OrganizationID, ProjectID: projectID})
	if errors.Is(err, pgx.ErrNoRows) {
		return ResolvedProject{}, toolExposureMissing()
	}
	if err != nil {
		return ResolvedProject{}, fmt.Errorf("resolve live tool exposure project: %w", err)
	}
	return ResolvedProject{ID: project.ID, Name: project.Name, Slug: project.Slug}, nil
}

// maxFrontingServers bounds how many servers one change may move. A toolset
// behind more servers than this is a shape the dashboard should resolve, not
// one to authorize in a loop of unbounded length.
const maxFrontingServers = 20

// authorizeEveryAffectedServer closes the gap between what the caller named
// and what the write actually moves. The tool list belongs to the toolset, so
// every live server fronting that toolset is an alias for the same list;
// checking only the named one would let write access to it change the tools of
// servers the caller was never authorized for.
func (s *MCPToolExposureService) authorizeEveryAffectedServer(ctx context.Context, projectID, named uuid.UUID, fronting []uuid.UUID) error {
	if len(fronting) > maxFrontingServers {
		return &MCPToolExposureError{
			Code:    "conflict",
			Message: "Too many MCP servers offer this same set of tools to change it from here. Edit it in the dashboard, where the shared set and the servers using it are shown together.",
			Cause:   ErrMCPToolExposureConflict,
		}
	}
	for _, id := range fronting {
		if id == named {
			continue
		}
		if err := s.engine.Require(ctx, authz.MCPCheck(authz.ScopeMCPWrite, id.String(), projectID.String())); err != nil {
			mapped := toolExposureAuthorizationError(err, authz.ScopeMCPWrite)
			if _, ok := errors.AsType[*ExternalAuthorizationError](mapped); !ok {
				return toolExposureUnavailable(err)
			}
			// The other servers are deliberately not named: the caller has not
			// cleared their boundary, and the count is what it needs in order
			// to understand the refusal.
			return &MCPToolExposureError{
				Code: "forbidden", Cause: err,
				Message: "Another MCP server offers this same set of tools, and changing it here would change that one too. You do not have permission to change every server it reaches, so nothing was changed.",
			}
		}
	}
	return nil
}

// requireKnownTools refuses the whole batch and names every tool that is
// neither generated by the project nor already on the server. Skipping them
// silently would report a no-op for a name the caller mistyped, which reads
// exactly like "that tool was already in the state you wanted".
func (s *MCPToolExposureService) requireKnownTools(ctx context.Context, queries *platformrepo.Queries, principal Principal, projectID uuid.UUID, requested []urn.Tool, exposed []string) error {
	values := toolURNStrings(requested)
	known, err := queries.ListPlatformMCPProjectToolURNs(ctx, platformrepo.ListPlatformMCPProjectToolURNsParams{
		ProjectID: projectID, OrganizationID: principal.OrganizationID, ToolUrns: values,
	})
	if err != nil {
		return fmt.Errorf("verify platform MCP project tools: %w", err)
	}
	present := make(map[string]bool, len(known)+len(exposed))
	for _, value := range known {
		present[value] = true
	}
	for _, value := range exposed {
		present[value] = true
	}
	var unknown []string
	for _, value := range values {
		if !present[value] {
			unknown = append(unknown, value)
		}
	}
	if len(unknown) == 0 {
		return nil
	}
	return &MCPToolExposureError{
		Code: "invalid_request", UnknownTools: unknown, Cause: ErrMCPToolExposureInvalid,
		Message: "Some of the named tools are neither produced by this project's latest deployment nor already on this MCP server, so nothing was changed. List the project's tools again; a tool pushed after that deployment finished is not available until the new one completes.",
	}
}

func (s *MCPToolExposureService) classifyTargetError(err error) error {
	if errors.Is(err, ErrMCPToolExposureMissing) {
		return toolExposureMissing()
	}
	if errors.Is(err, ErrUnavailable) {
		return toolExposureUnavailable(err)
	}
	return err
}

func classifyToolExposureError(err error) error {
	if shareable, ok := errors.AsType[*oops.ShareableError](err); ok {
		switch shareable.Code {
		case oops.CodeNotFound:
			return toolExposureMissing()
		case oops.CodeConflict:
			return toolExposureConflict()
		case oops.CodeBadRequest, oops.CodeInvalid:
			return toolExposureInvalid("That tool change is not valid for this MCP server.")
		case oops.CodeForbidden, oops.CodeUnauthorized:
			return &MCPToolExposureError{Code: "forbidden", Message: "You do not have permission to change which tools this MCP server exposes.", Cause: err}
		default:
			return toolExposureUnavailable(err)
		}
	}
	return fmt.Errorf("change MCP tool exposure: %w", err)
}

// toolExposureAdminAuthorizationError keeps a denial readable and turns
// everything else into the generic unavailable refusal. RequireLiveOrgAdmin
// wraps principal-resolution and grant-loading failures, which carry database
// detail; returning those unchanged would put them in front of an external MCP
// caller as the tool's error text.
func toolExposureAdminAuthorizationError(err error) error {
	mapped := toolExposureAuthorizationError(err, authz.ScopeOrgAdmin)
	if _, ok := errors.AsType[*ExternalAuthorizationError](mapped); ok {
		return mapped
	}
	return toolExposureUnavailable(err)
}

func toolExposureAuthorizationError(err error, scope authz.Scope) error {
	if shareable, ok := errors.AsType[*oops.ShareableError](err); ok && shareable.Code == oops.CodeForbidden {
		return &ExternalAuthorizationError{RequiredScope: string(scope), cause: err}
	}
	// RequireLiveOrgAdmin reports a lapsed membership as this package's own
	// forbidden sentinel rather than a shareable error; it is still a denial
	// and must carry the same required-permission challenge.
	if errors.Is(err, ErrForbidden) {
		return &ExternalAuthorizationError{RequiredScope: string(scope), cause: err}
	}
	return err
}

func toolExposureInvalid(message string) error {
	return &MCPToolExposureError{Code: "invalid_request", Message: message, Cause: ErrMCPToolExposureInvalid}
}

func toolExposureConflict() error {
	return &MCPToolExposureError{
		Code:    "conflict",
		Message: "This MCP server's tool list changed since it was read, so nothing was changed. Read the server again and repeat the request against the list it reports now.",
		Cause:   ErrMCPToolExposureConflict,
	}
}

func toolExposureMissing() error {
	return &MCPToolExposureError{
		Code:    "not_found",
		Message: "That MCP server is not one whose tool list can be changed from here. Only a server whose tools come from this project can be changed; a server that fronts an upstream, or one set up before this platform tracked servers separately, has to be edited in the dashboard.",
		Cause:   ErrMCPToolExposureMissing,
	}
}

func toolExposureUnavailable(cause error) error {
	return &MCPToolExposureError{
		Code:    unavailableCode,
		Message: "Changing which tools an MCP server exposes is temporarily unavailable.",
		Cause:   errors.Join(ErrUnavailable, cause),
	}
}

// toolExposureVersion binds the version token to the exact target and the
// exact list. Two toolsets at the same version number never share a token, and
// a list edited and reverted between reads yields the token it started with —
// which is the honest answer, because the committed list is the same one.
func toolExposureVersion(projectID, mcpServerID, toolsetID uuid.UUID, version int64, urns []string) string {
	sorted := slices.Clone(urns)
	slices.Sort(sorted)
	payload, err := json.Marshal(struct {
		ProjectID   string   `json:"project_id"`
		MCPServerID string   `json:"mcp_server_id"`
		ToolsetID   string   `json:"toolset_id"`
		Version     int64    `json:"version"`
		ToolURNs    []string `json:"tool_urns"`
	}{projectID.String(), mcpServerID.String(), toolsetID.String(), version, sorted})
	if err != nil {
		return ""
	}
	digest := sha256.Sum256(payload)
	return hex.EncodeToString(digest[:])
}

func toolURNStrings(tools []urn.Tool) []string {
	values := make([]string, 0, len(tools))
	for _, tool := range tools {
		values = append(values, tool.String())
	}
	return values
}

func boundedSummary(value string) string {
	trimmed := strings.TrimSpace(value)
	const limit = 240
	runes := []rune(trimmed)
	if len(runes) <= limit {
		return trimmed
	}
	return string(runes[:limit])
}

type toolInventoryCursor struct {
	OrganizationID string `json:"organization_id"`
	Binding        string `json:"binding"`
	ProjectID      string `json:"project_id"`
	Query          string `json:"query"`
	SourceKind     string `json:"source_kind"`
	AfterToolURN   string `json:"after_tool_urn"`
}

type toolInventoryCursorCodec struct {
	key []byte
}

func newToolInventoryCursorCodec(keyMaterial string) (*toolInventoryCursorCodec, error) {
	if keyMaterial == "" {
		return nil, ErrToolInventoryCursor
	}
	key := sha256.Sum256([]byte("platform-mcp-tool-inventory-cursor:" + keyMaterial))
	return &toolInventoryCursorCodec{key: key[:]}, nil
}

func (c *toolInventoryCursorCodec) Encode(cursor toolInventoryCursor) (string, error) {
	if c == nil || len(c.key) == 0 || cursor.OrganizationID == "" || cursor.Binding == "" || cursor.ProjectID == "" || cursor.AfterToolURN == "" {
		return "", ErrToolInventoryCursor
	}
	payload, err := json.Marshal(cursor)
	if err != nil {
		return "", fmt.Errorf("encode platform MCP tool inventory cursor: %w", err)
	}
	mac := hmac.New(sha256.New, c.key)
	_, _ = mac.Write(payload)
	token := make([]byte, 0, len(payload)+sha256.Size)
	token = append(token, payload...)
	token = append(token, mac.Sum(nil)...)
	return base64.RawURLEncoding.EncodeToString(token), nil
}

func (c *toolInventoryCursorCodec) Decode(value string, principal Principal, projectID uuid.UUID, query, sourceKind string) (string, error) {
	binding := principalCursorBinding(principal)
	if c == nil || len(c.key) == 0 || value == "" || principal.OrganizationID == "" || binding == "" || projectID == uuid.Nil {
		return "", ErrToolInventoryCursor
	}
	token, err := base64.RawURLEncoding.DecodeString(value)
	if err != nil || len(token) <= sha256.Size {
		return "", ErrToolInventoryCursor
	}
	payload, signature := token[:len(token)-sha256.Size], token[len(token)-sha256.Size:]
	mac := hmac.New(sha256.New, c.key)
	_, _ = mac.Write(payload)
	if !hmac.Equal(signature, mac.Sum(nil)) {
		return "", ErrToolInventoryCursor
	}
	var cursor toolInventoryCursor
	if err := json.Unmarshal(payload, &cursor); err != nil ||
		cursor.OrganizationID != principal.OrganizationID || cursor.Binding != binding ||
		cursor.ProjectID != projectID.String() || cursor.Query != query || cursor.SourceKind != sourceKind || cursor.AfterToolURN == "" {
		return "", ErrToolInventoryCursor
	}
	return cursor.AfterToolURN, nil
}
