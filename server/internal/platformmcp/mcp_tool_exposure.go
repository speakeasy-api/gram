const (
	operationAddMCPTools    = "add_mcp_tools"
	operationRemoveMCPTools = "remove_mcp_tools"

	// maxToolExposureBatch bounds one call so a single confirmation covers a
	// change a person can actually read back before approving it.
	maxToolExposureBatch = 50
	// maxExposedToolURNs bounds what one read returns. A larger list is
	// reported as truncated with its true count rather than silently cut.
	maxExposedToolURNs = 200

	toolExposureFeature = "mcp_tool_exposure"
)

var (
	ErrMCPToolExposureInvalid  = errors.New("invalid MCP tool exposure request")
	ErrMCPToolExposureConflict = errors.New("MCP tool list changed")
	ErrMCPToolExposureMissing  = errors.New("MCP tool exposure target not found")
	ErrToolInventoryCursor     = errors.New("invalid platform mcp tool inventory cursor")
)

// MCPToolExposureError is safe to map into a tool refusal. UnknownTools names
// the exact tools that were refused, so a caller never has to guess which part
// of its batch was rejected and never sees a partially applied batch.
type MCPToolExposureError struct {
	Code         string
	Message      string
	UnknownTools []string
	Cause        error
}

func (e *MCPToolExposureError) Error() string { return e.Message }
func (e *MCPToolExposureError) Unwrap() error { return e.Cause }

// ProjectTool is one generated tool definition in a project, named by the
// stable URN that every exposure call takes.
type ProjectTool struct {
	Name string `json:"name"`
	URN  string `json:"urn"`
	// Summary is the tool's own short description, trimmed to keep a page of
	// results readable. It carries no configuration or credential material.
	Summary string `json:"summary,omitempty"`
	// SourceKind is "function" or "openapi": which kind of source produced
	// this tool.
	SourceKind string `json:"source_kind"`
	SourceSlug string `json:"source_slug,omitempty"`
	SourceName string `json:"source_name,omitempty"`
}

type ListProjectToolsInput struct {
	ProjectID  string `json:"project_id" jsonschema:"project ID whose tools to list"`
	Query      string `json:"query,omitempty" jsonschema:"optional match on tool name, tool URN, or source slug"`
	SourceKind string `json:"source_kind,omitempty" jsonschema:"optional source filter: function or openapi"`
	Cursor     string `json:"cursor,omitempty" jsonschema:"opaque cursor returned by a previous list_project_tools result"`
	Limit      int    `json:"limit,omitempty" jsonschema:"maximum number of tools to return; server clamps this to 100"`
}

type ListProjectToolsOutput struct {
	ProjectID string `json:"project_id"`
	// DeploymentID is the deployment these tools were generated by. A tool
	// pushed after that deployment finished appears only once the new
	// deployment completes.
	DeploymentID string        `json:"deployment_id,omitempty"`
	Tools        []ProjectTool `json:"tools"`
	NextCursor   string        `json:"next_cursor,omitempty"`
}

// MCPToolExposure is the tool list one hosted MCP server currently exposes.
// It is present on get_mcp and absent from find_mcp: a list result reports
// which servers exist, not what each one exposes, and an empty list there
// would read as "exposes nothing" rather than "not read".
type MCPToolExposure struct {
	ToolsetID   string `json:"toolset_id"`
	ToolsetSlug string `json:"toolset_slug"`
	// ExposureVersion identifies the exact tool list this snapshot describes.
	// add_tools_to_mcp and remove_tools_from_mcp take it back and refuse a
	// change computed against a list that has since moved on.
	ExposureVersion string   `json:"exposure_version"`
	ToolCount       int      `json:"tool_count"`
	ToolURNs        []string `json:"tool_urns"`
	Truncated       bool     `json:"truncated"`
	// SharedWithOther counts the other MCP servers offering this same tool
	// list. The list lives on the toolset behind the server, so those servers
	// are aliases for it and a change moves all of them. It is a count rather
	// than a list of servers: the number is what a caller needs in order to
	// warn, and naming servers would report them to a caller admitted only on
	// this one.
	SharedWithOther int `json:"shared_with_other_servers"`

	// toolsetVersion is the version-chain number behind ExposureVersion. It
	// stays internal: a caller passes the opaque token back, and only the
	// toolsets package reasons about the chain itself.
	toolsetVersion int64
}

type ChangeMCPToolsInput struct {
	ProjectID       string   `json:"project_id" jsonschema:"project ID that owns the MCP server"`
	MCPID           string   `json:"mcp_id" jsonschema:"exact MCP server ID from find_mcp or get_mcp"`
	ToolURNs        []string `json:"tool_urns" jsonschema:"exact tool URNs from list_project_tools"`
	ExpectedVersion string   `json:"expected_version" jsonschema:"exposure_version from the latest get_mcp read of this server"`
	IdempotencyKey  string   `json:"idempotency_key" jsonschema:"caller-chosen key that makes a retry of this exact change safe"`
	Confirmed       bool     `json:"confirmed" jsonschema:"true only after the user confirmed this exact server and tool list"`
}

// MCPToolExposureMutationOutput lets a caller tell four outcomes apart:
// applied (Outcome "applied"), a no-op because every named tool was already in
// the requested state (Outcome "no_op"), a partial batch (Outcome "applied"
// with a non-empty Unchanged), and a refusal, which is returned as an error
// result and never as this struct.
type MCPToolExposureMutationOutput struct {
	Outcome   string   `json:"outcome"`
	Applied   []string `json:"applied"`
	Unchanged []string `json:"unchanged"`
	// Exposure is a fresh read taken after the commit, so a caller reports the
	// committed list rather than the one it asked for.
	Exposure      *MCPToolExposure `json:"exposure,omitempty"`
	SnapshotScope string           `json:"snapshot_scope"`
	// Distributions names the plugins that carry this server. Changing the
	// tool list republishes each of them to everyone holding that plugin.
	Distributions      []MCPDistribution       `json:"distributions"`
	PublicationRequest string                  `json:"publication_request"`
	PublishSignal      string                  `json:"publish_signal"`
	Receipt            RiskMutationToolReceipt `json:"receipt"`
}

// MCPToolExposureService reads what a project can expose and what one server
// exposes, and applies incremental changes to the latter.
type MCPToolExposureService struct {
	db      *pgxpool.Pool
	queries *platformrepo.Queries
	logger  *slog.Logger
	audit   *audit.Logger
	// engine checks the resource-scoped mcp:write grant, exactly as the
	// dashboard's own toolset update does.
	engine *authz.Engine
	// admin re-checks org:admin live through the shared authorizer, so a
	// denial keeps the challenge and audit behavior every other
	// admin-gated Platform MCP path records.
	admin       Authorizer
	cursors     *toolInventoryCursorCodec
	publication plugins.PublicationRequests
	publisher   plugins.PluginPublishSignaler
	now         func() time.Time
}

func NewMCPToolExposureService(logger *slog.Logger, db *pgxpool.Pool, auditLogger *audit.Logger, engine *authz.Engine, admin Authorizer, cursorKeyMaterial string, publication plugins.PublicationRequests, publisher plugins.PluginPublishSignaler) (*MCPToolExposureService, error) {
	if logger == nil || db == nil || auditLogger == nil || engine == nil || admin == nil {
		return nil, ErrMCPToolExposureInvalid
	}
	cursors, err := newToolInventoryCursorCodec(cursorKeyMaterial)
	if err != nil {
		return nil, err
	}
	return &MCPToolExposureService{
		db: db, queries: platformrepo.New(db), logger: logger, audit: auditLogger, engine: engine, admin: admin,
		cursors: cursors, publication: publication, publisher: publisher, now: time.Now,
	}, nil
}

func (s *MCPToolExposureService) valid() bool {
	return s != nil && s.db != nil && s.queries != nil && s.audit != nil && s.engine != nil && s.admin != nil && s.cursors != nil && s.now != nil
}

// ListProjectTools reports the tools a project's latest completed deployment
// generated. The caller must already hold project read.
func (s *MCPToolExposureService) ListProjectTools(ctx context.Context, principal Principal, project ResolvedProject, input ListProjectToolsInput) (ListProjectToolsOutput, error) {
	if !s.valid() {
		return ListProjectToolsOutput{}, ErrUnavailable
	}
	sourceKind := strings.ToLower(strings.TrimSpace(input.SourceKind))
	if sourceKind != "" && sourceKind != "function" && sourceKind != "openapi" {
		return ListProjectToolsOutput{}, toolExposureInvalid("source_kind must be function or openapi.")
	}
	query := strings.TrimSpace(input.Query)
	after := ""
	if input.Cursor != "" {
		decoded, err := s.cursors.Decode(input.Cursor, principal, project.ID, query, sourceKind)
		if err != nil {
			return ListProjectToolsOutput{}, toolExposureInvalid("That page marker is no longer valid. List the project's tools again from the start.")
		}
		after = decoded
	}
	limit := boundedLimit(input.Limit)
	rows, err := s.queries.ListPlatformMCPProjectTools(ctx, platformrepo.ListPlatformMCPProjectToolsParams{
		ProjectID:      project.ID,
		OrganizationID: principal.OrganizationID,
		AfterToolUrn:   optionalText(after),
		SourceKind:     optionalText(sourceKind),
		QueryText:      query,
		LimitValue:     int32(limit) + 1, //nolint:gosec // boundedLimit clamps to 100.
	})
	if err != nil {
		return ListProjectToolsOutput{}, fmt.Errorf("list platform MCP project tools: %w", err)
	}
	page, truncated := boundedRows(rows, limit)
	output := ListProjectToolsOutput{ProjectID: project.ID.String(), Tools: make([]ProjectTool, 0, len(page))}
	for _, row := range page {
		if row.DeploymentID != uuid.Nil {
			output.DeploymentID = row.DeploymentID.String()
		}
		output.Tools = append(output.Tools, ProjectTool{
			Name: row.ToolName, URN: row.ToolUrn, Summary: boundedSummary(row.Summary),
			SourceKind: row.SourceKind, SourceSlug: row.SourceSlug, SourceName: row.SourceName,
		})
	}
	if truncated && len(page) > 0 {
		cursor, err := s.cursors.Encode(toolInventoryCursor{
			OrganizationID: principal.OrganizationID, Binding: principalCursorBinding(principal),
			ProjectID: project.ID.String(), Query: query, SourceKind: sourceKind,
			AfterToolURN: page[len(page)-1].ToolUrn,
		})
		if err != nil {
			return ListProjectToolsOutput{}, fmt.Errorf("encode platform MCP tool inventory cursor: %w", err)
		}
		output.NextCursor = cursor
	}
	return output, nil
}

// Exposure reads the tool list of one hosted MCP server. It returns
// ErrMCPToolExposureMissing when the server has no Gram toolset behind it:
// a remote, tunneled, or unproxied server's tools come from its upstream.
func (s *MCPToolExposureService) Exposure(ctx context.Context, principal Principal, projectID, mcpID uuid.UUID) (MCPToolExposure, error) {
	if !s.valid() {
		return MCPToolExposure{}, ErrUnavailable
	}
	return s.exposure(ctx, s.queries, principal, projectID, mcpID)
}

// exposureRow is the untruncated read. The public projection bounds the tool
// list it reports, so anything that has to reason about the whole committed
// list — the version token, the removable set — uses the row instead.
func (s *MCPToolExposureService) exposureRow(ctx context.Context, queries *platformrepo.Queries, principal Principal, projectID, mcpID uuid.UUID) (platformrepo.GetPlatformMCPServerToolExposureRow, error) {
	row, err := queries.GetPlatformMCPServerToolExposure(ctx, platformrepo.GetPlatformMCPServerToolExposureParams{
		OrganizationID: principal.OrganizationID, McpServerID: mcpID, ProjectID: projectID,
	})
	if errors.Is(err, pgx.ErrNoRows) {
		return platformrepo.GetPlatformMCPServerToolExposureRow{}, ErrMCPToolExposureMissing
	}
	if err != nil {
		return platformrepo.GetPlatformMCPServerToolExposureRow{}, fmt.Errorf("get platform MCP server tool exposure: %w", err)
	}
	return row, nil
}

func (s *MCPToolExposureService) exposure(ctx context.Context, queries *platformrepo.Queries, principal Principal, projectID, mcpID uuid.UUID) (MCPToolExposure, error) {
	row, err := s.exposureRow(ctx, queries, principal, projectID, mcpID)
	if err != nil {
		return MCPToolExposure{}, err
	}
	return toolExposureFromRow(projectID, mcpID, row), nil
}

func toolExposureFromRow(projectID, mcpID uuid.UUID, row platformrepo.GetPlatformMCPServerToolExposureRow) MCPToolExposure {
	urns, truncated := boundedRows(row.ToolUrns, maxExposedToolURNs)
	return MCPToolExposure{
		ToolsetID:       row.ToolsetID.String(),
		ToolsetSlug:     row.ToolsetSlug,
		ExposureVersion: toolExposureVersion(projectID, mcpID, row.ToolsetID, row.ToolsetVersion, row.ToolUrns),
		ToolCount:       len(row.ToolUrns),
		ToolURNs:        slices.Clone(urns),
		Truncated:       truncated,
		SharedWithOther: max(len(row.FrontingServerIds)-1, 0),
		toolsetVersion:  row.ToolsetVersion,
	}
}

