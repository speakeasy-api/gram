package remotesessions

import (
	"strings"

	"github.com/jackc/pgx/v5/pgtype"

	"github.com/speakeasy-api/gram/server/internal/idpmanaged"
	"github.com/speakeasy-api/gram/server/internal/oops"
	"github.com/speakeasy-api/gram/server/internal/remotesessions/repo"
)

// correctedClientID returns the client_id an update replaces the stored one
// with, or an invalid value when the update leaves it as it is. Correcting the
// value fixes a mistyped manual entry; it does not register anything with the
// issuer. CIMD clients are refused because their client_id is the metadata
// document URL Speakeasy generated, and managed clients because their
// registration belongs to the identity provider connection.
func correctedClientID(existing repo.RemoteSessionClient, requested *string) (pgtype.Text, error) {
	if requested == nil {
		return pgtype.Text{String: "", Valid: false}, nil
	}

	clientID := strings.TrimSpace(*requested)
	if clientID == "" {
		return pgtype.Text{String: "", Valid: false}, oops.E(oops.CodeBadRequest, nil, "client_id cannot be empty")
	}
	if clientID == existing.ClientID {
		return pgtype.Text{String: "", Valid: false}, nil
	}

	if existing.ClientIDMetadataUri.Valid {
		return pgtype.Text{String: "", Valid: false}, oops.E(oops.CodeBadRequest, nil, "the client_id of a Client ID Metadata Document client is generated by Speakeasy and cannot be changed")
	}
	if err := idpmanaged.RequireUnmanaged(existing.IdentityProviderConnectionID, "this remote session client"); err != nil {
		return pgtype.Text{String: "", Valid: false}, err
	}

	return pgtype.Text{String: clientID, Valid: true}, nil
}

// updatedDisplayName trims a requested display name. An empty result is kept
// as an empty string, which the update queries store as NULL so the client
// falls back to its client_id.
func updatedDisplayName(requested *string) pgtype.Text {
	if requested == nil {
		return pgtype.Text{String: "", Valid: false}
	}

	return pgtype.Text{String: strings.TrimSpace(*requested), Valid: true}
}
