// Package email is the application-facing facade for sending transactional
// emails. It defines strongly typed templates and resolves their stable logical
// keys to environment-specific Loops IDs supplied by the deployment.
//
// Adding a new template
//
//  1. Add a TemplateKey constant to this file.
//  2. Add a template_<name>.go type whose exported fields are the variables
//     consumed by the template.
//  3. Implement Template: Key, Variables, and AddToAudience.
//  4. Append its zero value to RegisteredTemplates.
//  5. Add its LMX source and metadata to loops/manifest.json.
package email

import (
	"encoding/json"
	"errors"
	"fmt"
)

// TemplateKey is the stable application-owned identity of an email template.
// Unlike a Loops ID, it is identical in every deployment environment.
type TemplateKey string

// TransactionalID is the opaque environment-specific identifier assigned by
// Loops when CI creates a transactional email.
type TransactionalID string

const (
	TemplateKeyTeamInvite                TemplateKey = "team_invite"
	TemplateKeyEnterpriseAdminOnboarding TemplateKey = "enterprise_admin_onboarding"
	TemplateKeyTumUsageThreshold         TemplateKey = "tum_usage_threshold"
	TemplateKeyTumUsageOverage           TemplateKey = "tum_usage_overage"
	TemplateKeyOpenRouterChatCredits     TemplateKey = "openrouter_chat_credits_threshold"
	TemplateKeyOpenRouterInternalCredits TemplateKey = "openrouter_internal_credits_threshold"
	TemplateKeyCustomDomainUnhealthy     TemplateKey = "custom_domain_unhealthy"
	TemplateKeyWeeklyUsageSummary        TemplateKey = "weekly_usage_summary"
	TemplateKeyAccessRequest             TemplateKey = "access_request"
	TemplateKeyTrialEndingSoon           TemplateKey = "trial_ending_soon"
	TemplateKeyAccessPaused              TemplateKey = "access_paused"
	TemplateKeyPaygActivated             TemplateKey = "payg_activated"
)

var (
	ErrEmptyTemplateIDs   = errors.New("email: template ID mapping is empty")
	ErrUnknownTemplateKey = errors.New("email: template ID mapping contains an unknown key")
)

// TemplateIDs maps application-owned keys to IDs in one Loops environment.
// It is generated by release CI and injected into server and worker as JSON.
type TemplateIDs map[TemplateKey]TransactionalID

// NewTemplateIDs builds a typed mapping from string configuration or test
// values without requiring callers to enumerate every TemplateKey constant.
func NewTemplateIDs(values map[string]string) TemplateIDs {
	ids := make(TemplateIDs, len(values))
	for key, id := range values {
		ids[TemplateKey(key)] = TransactionalID(id)
	}
	return ids
}

// ParseTemplateIDs parses the JSON mapping injected by the Helm chart. An
// empty value is accepted for local development, where Loops is disabled.
func ParseTemplateIDs(raw string) (TemplateIDs, error) {
	if raw == "" {
		return make(TemplateIDs), nil
	}

	var values map[string]string
	if err := json.Unmarshal([]byte(raw), &values); err != nil {
		return nil, fmt.Errorf("parse email template IDs: %w", err)
	}

	return NewTemplateIDs(values), nil
}

// ValidateRegistered requires one non-empty ID for every registered template
// and rejects unknown keys. Production processes call this when Loops is on.
func (ids TemplateIDs) ValidateRegistered() error {
	if len(ids) == 0 {
		return ErrEmptyTemplateIDs
	}

	registered := make(map[TemplateKey]struct{}, len(RegisteredTemplates))
	for _, tmpl := range RegisteredTemplates {
		key := tmpl.Key()
		registered[key] = struct{}{}
		if ids[key] == "" {
			return fmt.Errorf("email: no Loops ID for template %q", key)
		}
	}

	for key := range ids {
		if _, ok := registered[key]; !ok {
			return fmt.Errorf("%w: %q", ErrUnknownTemplateKey, key)
		}
	}

	return nil
}

// Template is implemented by every concrete transactional email.
type Template interface {
	// Key returns the stable application-owned template identity.
	Key() TemplateKey
	// Variables returns the merge data Loops substitutes into the template.
	Variables() map[string]string
	// AddToAudience reports whether the recipient should be upserted as a
	// Loops contact when the email is sent.
	AddToAudience() bool
}

