type hooksBinaryTarget struct {
	URL    string `json:"url"`
	SHA256 string `json:"sha256"`
}

// hooksReleaseTargets derives each target's immutable release-artifact URL
// from the version so a version bump can never skew from the pinned URLs.
func hooksReleaseTargets(version string, sha256s map[string]string) map[string]hooksBinaryTarget {
	out := make(map[string]hooksBinaryTarget, len(sha256s))
	for target, sha := range sha256s {
		out[target] = hooksBinaryTarget{
			URL:    fmt.Sprintf("https://github.com/speakeasy-api/gram/releases/download/hooks%%40%s/speakeasy-hooks_%s.zip", version, strings.ReplaceAll(target, "-", "_")),
			SHA256: sha,
		}
	}
	return out
}

// hooksBinaryTargets is the UPSTREAM artifact set: the GitHub release URLs the
// server itself fetches from (see HooksArtifactServer). Bootstrap scripts never
// see these URLs — they download from the org's Gram server domain via
// hooksServedTargets, because customer environments (notably Claude Cowork's
// sandbox) often cannot reach GitHub while the Gram domain is already
// allowlisted for ingest.
var hooksBinaryTargets = hooksReleaseTargets(hooksBinaryVersion, hooksBinarySHA256s)

func renderHooksConfig(cfg GenerateConfig) ([]byte, error) {
	b, err := json.MarshalIndent(relay.FileConfig{
		ServerURL: cfg.ServerURL,
		// Browser sign-in origin, only used by the relay's interactive login.
		// Server-generated plugins authenticate with the baked HooksAPIKey, so
		// there is no site URL to bake; omitempty drops it from the JSON.
		SiteURL:      "",
		Project:      cfg.ProjectSlug,
		Org:          cfg.OrgID,
		HooksAPIKey:  cfg.HooksAPIKey,
		BrowserLogin: cfg.BrowserLogin,
		// Legacy observability-mode flag; new plugins never set it. Outage
		// tolerance flows to the binary at run time via ingest effects
		// (hooks_fail_open), not through baked configuration.
		Nonblocking: false,
	}, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("marshal speakeasy.json: %w", err)
	}
	return append(b, '\n'), nil
}

// hooksServedTargets derives the download URLs baked into bootstrap scripts:
// the pinned artifacts as served by the org's own Gram server (see
// HooksArtifactServer), keeping the checksums from the upstream pin.
func hooksServedTargets(serverURL string) map[string]hooksBinaryTarget {
	base := strings.TrimRight(serverURL, "/")
	out := make(map[string]hooksBinaryTarget, len(hooksBinaryTargets))
	for target, asset := range hooksBinaryTargets {
		out[target] = hooksBinaryTarget{
			URL:    fmt.Sprintf("%s%s%s/speakeasy-hooks_%s.zip", base, HooksReleaseRoutePrefix, hooksBinaryVersion, strings.ReplaceAll(target, "-", "_")),
			SHA256: asset.SHA256,
		}
	}
	return out
}

// hooksDownloadHost names the host administrators must allow for cold installs
// in the install-failure hint. Falls back to the raw server URL when it does
// not parse as an absolute URL.
func hooksDownloadHost(serverURL string) string {
	if u, err := url.Parse(serverURL); err == nil && u.Host != "" {
		return u.Host
	}
	return serverURL
}

func renderHooksBootstrap(cfg GenerateConfig) []byte {
	return renderHooksBootstrapForRelease(hooksBinaryVersion, hooksServedTargets(cfg.ServerURL), cfg.InstallFailOpen, hooksDownloadHost(cfg.ServerURL))
}

// renderHooksBootstrapForRelease renders the Unix bootstrap script. failOpen
// selects the org's install-failure policy: when true, every distribution
// failure (download, missing tooling, lock-wait timeout, checksum mismatch)
// exits 0 so providers treat the hook as passed; when false it exits 1 and
// decision-capable hooks fail per provider semantics. A checksum mismatch
// never executes the artifact under either policy. downloadHost names the host
// to allowlist in the install-failure hint.
func renderHooksBootstrapForRelease(version string, targets map[string]hooksBinaryTarget, failOpen bool, downloadHost string) []byte {
	var cases strings.Builder
	keys := make([]string, 0, len(targets))
	for target := range targets {
		keys = append(keys, target)
	}
	sort.Strings(keys)
	for _, target := range keys {
		asset := targets[target]
		fmt.Fprintf(&cases, "  %s) url=%q; expected_sha=%q ;;\n", target, asset.URL, asset.SHA256)
	}

	return fmt.Appendf(nil, `#!/usr/bin/env bash
# Generated by Speakeasy. Downloads one pinned, checksum-verified hooks binary.
set -eu

version=%q
install_failure_exit=%d

install_failure() {
  printf 'speakeasy-hooks: %%s\n' "$1" >&2
  printf 'speakeasy-hooks: ask your administrator to allow downloads from %s, or preinstall the hooks binary (GRAM_HOOKS_HOME overrides the cache location)\n' >&2
  exit "$install_failure_exit"
}

# Codex plugin versions are disposable. When its inline command supplies a
# stable data root, publish this script and its deployment config there before
# doing any other work, then run the relay against the stable config. A failed
# persistence attempt must not break a hook whose installed payload still works.
persist_root=${SPEAKEASY_HOOKS_PERSIST_ROOT:-}
source_script=${SPEAKEASY_HOOKS_PERSIST_SCRIPT:-}
source_config=${SPEAKEASY_HOOKS_PERSIST_CONFIG:-}
config_arg_index=0
arg_index=0
for arg in "$@"; do
  case "$arg" in
    --config=*) config_arg_index=$arg_index; break ;;
  esac
  arg_index=$((arg_index + 1))
done

persist_payload() {
  [ -n "$persist_root" ] && [ -r "$source_script" ] && [ -r "$source_config" ] || return 1
  generations="$persist_root/generations"
  current="$persist_root/.unix-current"
  lock="$persist_root/.persist-unix.lock"
  umask 077
  mkdir -p "$generations" || return 1
  chmod 700 "$persist_root" "$generations" 2>/dev/null || true
  current_generation=
  IFS= read -r current_generation < "$current" 2>/dev/null || current_generation=
  case "$current_generation" in ''|*/*) current_generation= ;; esac
  current_dir="$generations/$current_generation"
  if [ -n "$current_generation" ] && [ -r "$current_dir/hooks/bootstrap.sh" ] &&
     [ -r "$current_dir/speakeasy.json" ]; then
    published_script="$current_dir/hooks/bootstrap.sh"
    published_config="$current_dir/speakeasy.json"
    if cmp -s "$source_script" "$published_script" && cmp -s "$source_config" "$published_config"; then
      return 0
    fi
  fi

  own_lock=
  if mkdir "$lock" 2>/dev/null; then
    if printf '%%s\n' "$$" > "$lock/pid"; then
      own_lock=1
    else
      rm -rf "$lock"
    fi
  else
    stale=
    owner_pid=
    owner_valid=
    if [ -r "$lock/pid" ]; then
      IFS= read -r owner_pid < "$lock/pid" || owner_pid=
      case "$owner_pid" in
        ''|*[!0-9]*) ;;
        *) owner_valid=1; kill -0 "$owner_pid" 2>/dev/null || stale=1 ;;
      esac
    fi
    # Publishing only copies two local files. Expire any old lease so a hung
    # owner or a recycled PID cannot freeze refresh indefinitely.
    if [ -n "$(find "$lock" -maxdepth 0 -mmin +5 2>/dev/null)" ]; then
      stale=1
    fi
    if [ -n "$stale" ]; then
      reap="${lock}.stale.$$"
      if mv "$lock" "$reap" 2>/dev/null; then
        rm -rf "$reap"
        if mkdir "$lock" 2>/dev/null; then
          if printf '%%s\n' "$$" > "$lock/pid"; then
            own_lock=1
          else
            rm -rf "$lock"
          fi
        fi
      fi
    fi
  fi

  if [ -z "$own_lock" ]; then
    # Another hook publishing the same bundle wins. The current pointer only
    # ever names a generation that was completely written before publication.
    [ -n "${published_config:-}" ]
    return
  fi

  generation="unix-$(date +%%s)-$$"
  generation_dir="$generations/$generation"
  hooks_dir="$generation_dir/hooks"
  current_tmp="$persist_root/.unix-current.$$"
  persisted=
  if mkdir -p "$hooks_dir" && cp "$source_script" "$hooks_dir/bootstrap.sh" &&
     cp "$source_config" "$generation_dir/speakeasy.json" &&
     chmod 700 "$generation_dir" "$hooks_dir" "$hooks_dir/bootstrap.sh" &&
     chmod 600 "$generation_dir/speakeasy.json" &&
     printf '%%s\n' "$generation" > "$current_tmp" && mv "$current_tmp" "$current"; then
      persisted=1
      published_script="$hooks_dir/bootstrap.sh"
      published_config="$generation_dir/speakeasy.json"
      [ "$source_script" = "$0" ] || reexec_stable=1
  fi
  [ -n "$persisted" ] || rm -rf "$generation_dir"
  rm -f "$current_tmp"
  rm -rf "$lock"
  [ -n "$persisted" ]
}

if [ -n "$source_config" ] && persist_payload; then
  forwarded=()
  arg_index=0
  for arg in "$@"; do
    if [ "$arg_index" -eq "$config_arg_index" ]; then
      forwarded+=("--config=$published_config")
    else
      forwarded+=("$arg")
    fi
    arg_index=$((arg_index + 1))
  done
  set -- "${forwarded[@]}"
fi

if [ -n "${reexec_stable:-}" ]; then
  unset SPEAKEASY_HOOKS_PERSIST_ROOT SPEAKEASY_HOOKS_PERSIST_SCRIPT SPEAKEASY_HOOKS_PERSIST_CONFIG
  exec bash "$published_script" "$@"
fi

case "$(uname -s)" in
  Darwin) os=darwin ;;
  Linux) os=linux ;;
  MINGW*|MSYS*|CYGWIN*) os=windows ;;
  *) install_failure 'unsupported operating system' ;;
esac
case "$(uname -m)" in
  x86_64|amd64) arch=amd64 ;;
  arm64|aarch64) arch=arm64 ;;
  *) install_failure 'unsupported architecture' ;;
esac
target="${os}-${arch}"
case "$target" in
%s  *) install_failure "unsupported target ${target}" ;;
esac

if [ -n "${GRAM_HOOKS_HOME:-}" ]; then
  cache_root=$GRAM_HOOKS_HOME
elif [ "$os" = darwin ]; then
  cache_root="${HOME}/Library/Caches/Speakeasy/hooks"
elif [ "$os" = windows ] && [ -n "${LOCALAPPDATA:-}" ]; then
  cache_root="${LOCALAPPDATA}/Speakeasy/hooks"
else
  cache_root="${XDG_CACHE_HOME:-${HOME}/.cache}/speakeasy/hooks"
fi

install_dir="${cache_root}/${version}/${target}"
binary_name=speakeasy-hooks
[ "$os" = windows ] && binary_name=speakeasy-hooks.exe
binary="${install_dir}/${binary_name}"
marker="${install_dir}/archive.sha256"

# The PowerShell bootstrapper shares this cache on Windows: tolerate a marker
# with a CRLF ending or no trailing newline.
cache_valid() {
  [ -x "$binary" ] && [ -r "$marker" ] || return 1
  cached_sha=
  IFS= read -r cached_sha < "$marker" || true
  cached_sha=${cached_sha%%$'\r'}
  [ -n "$cached_sha" ] && [ "$cached_sha" = "$expected_sha" ]
}

if cache_valid; then
  exec "$binary" "$@"
fi

mkdir -p "$(dirname "$install_dir")" || install_failure 'could not create the cache directory'
lock="${install_dir}.lock"
waited=0
while ! mkdir "$lock" 2>/dev/null; do
  if cache_valid; then
    exec "$binary" "$@"
  fi
  stale=
  if [ -r "$lock/pid" ]; then
    IFS= read -r owner_pid < "$lock/pid" || owner_pid=
    case "$owner_pid" in
      *[!0-9]*|'') ;;
      *) kill -0 "$owner_pid" 2>/dev/null || stale=1 ;;
    esac
  fi
  # An owner that died before writing its pid (or a PowerShell owner, which
  # writes none) leaves no process to probe; reclaim such locks by age.
  # Legitimate installs finish well under this threshold.
  if [ -z "$stale" ] && [ -n "$(find "$lock" -maxdepth 0 -mmin +5 2>/dev/null)" ]; then
    stale=1
  fi
  if [ -n "$stale" ]; then
    rm -rf "$lock"
    continue
  fi
  # Providers kill blocking hooks at around 60 seconds; give up before that so
  # the outcome is the configured install-failure policy, not an opaque
  # provider timeout.
  if [ "$waited" -ge 45 ]; then
    install_failure 'timed out waiting for a concurrent installation'
  fi
  sleep 1
  waited=$((waited + 1))
done
printf '%%s\n' "$$" > "$lock/pid"

work=
cleanup() {
  [ -z "$work" ] || rm -rf "$work"
  rm -rf "$lock"
}
trap cleanup EXIT HUP INT TERM

# Another process may have completed between the warm-path check and lock claim.
if ! cache_valid; then
  work=$(mktemp -d "$(dirname "$install_dir")/.speakeasy-hooks.XXXXXX") || install_failure 'could not create a working directory'
  archive="${work}/hooks.zip"
  # The download budget must stay under the ~60s provider hook kill (same
  # reasoning as the lock wait) so a stalled network lands on the configured
  # install-failure policy instead of an opaque provider timeout.
  if command -v curl >/dev/null 2>&1; then
    curl --fail --silent --show-error --location --connect-timeout 10 --max-time 45 "$url" --output "$archive" || install_failure 'download failed'
  elif command -v wget >/dev/null 2>&1; then
    # wget --timeout is a per-read timeout, not a wall-clock cap: a server that
    # trickles bytes resets it indefinitely. timeout(1) enforces the real
    # deadline wherever coreutils/busybox provide it.
    wget_cmd="wget -q --timeout=45 --tries=1"
    if command -v timeout >/dev/null 2>&1; then
      wget_cmd="timeout 45 $wget_cmd"
    fi
    $wget_cmd "$url" -O "$archive" || install_failure 'download failed'
  else
    install_failure 'curl or wget is required for first install'
  fi

  if command -v sha256sum >/dev/null 2>&1; then
    actual_sha=$(sha256sum "$archive" | cut -d ' ' -f 1) || install_failure 'checksum computation failed'
  elif command -v shasum >/dev/null 2>&1; then
    actual_sha=$(shasum -a 256 "$archive" | cut -d ' ' -f 1) || install_failure 'checksum computation failed'
  elif command -v openssl >/dev/null 2>&1; then
    actual_sha=$(openssl dgst -sha256 "$archive" | sed 's/^.*= //') || install_failure 'checksum computation failed'
  else
    install_failure 'no SHA-256 utility is available'
  fi
  if [ "$actual_sha" != "$expected_sha" ]; then
    install_failure 'downloaded archive checksum mismatch'
  fi

  extracted="${work}/${binary_name}"
  if command -v unzip >/dev/null 2>&1; then
    unzip -p "$archive" "$binary_name" > "$extracted" || install_failure 'archive extraction failed'
  elif command -v busybox >/dev/null 2>&1; then
    busybox unzip -p "$archive" "$binary_name" > "$extracted" || install_failure 'archive extraction failed'
  else
    install_failure 'unzip is required for first install'
  fi
  chmod 755 "$extracted" || install_failure 'could not mark the binary executable'
  mkdir -p "$install_dir" || install_failure 'could not create the install directory'
  mv "$extracted" "$binary" || install_failure 'could not install the binary'
  printf '%%s\n' "$expected_sha" > "${work}/archive.sha256" || install_failure 'could not record the installed checksum'
  mv "${work}/archive.sha256" "$marker" || install_failure 'could not record the installed checksum'
fi

trap - EXIT HUP INT TERM
cleanup
exec "$binary" "$@"
`, version, conv.Ternary(failOpen, 0, 1), downloadHost, cases.String())
}

// renderHooksPowerShellBootstrap renders the Windows bootstrap script. It
// mirrors the Unix script's cache layout, directory-based lock protocol, and
// install-failure policy so both can share one cache on machines that also
// run hooks under Git Bash.
func renderHooksPowerShellBootstrap(cfg GenerateConfig) []byte {
	served := hooksServedTargets(cfg.ServerURL)
	var cases strings.Builder
	for _, arch := range []string{"amd64", "arm64"} {
		asset := served["windows-"+arch]
		fmt.Fprintf(&cases, "    %q { $Url = %q; $ExpectedSha = %q }\n", arch, asset.URL, asset.SHA256)
	}

	return fmt.Appendf(nil, `# Generated by Speakeasy. Downloads one pinned, checksum-verified hooks binary.
$ErrorActionPreference = "Stop"
$ProgressPreference = "SilentlyContinue"
$ForwardArgs = @($args)
$Version = %q
$InstallFailureExit = %d

function Exit-InstallFailure([string]$Message) {
    [Console]::Error.WriteLine("speakeasy-hooks: $Message")
    [Console]::Error.WriteLine("speakeasy-hooks: ask your administrator to allow downloads from %s, or preinstall the hooks binary (GRAM_HOOKS_HOME overrides the cache location)")
    exit $InstallFailureExit
}

# Codex supplies a version-independent plugin data directory. Publish this
# launcher and its deployment config there as one ready-marked bundle, then run
# the relay against the stable config. Persistence failure leaves the installed
# payload usable for the current invocation.
function Enter-PersistenceLock([string]$LockPath) {
    $Created = $false
    try {
        New-Item -ItemType Directory -Path $LockPath -ErrorAction Stop | Out-Null
        $Created = $true
        [System.IO.File]::WriteAllText((Join-Path $LockPath "pid"), "$PID" + [char]10)
        return $true
    } catch {
        if ($Created) {
            Remove-Item -LiteralPath $LockPath -Recurse -Force -ErrorAction SilentlyContinue
        }
    }

    $Stale = $false
    try {
        $LockInfo = Get-Item -LiteralPath $LockPath -ErrorAction Stop
        $Expired = ([DateTime]::UtcNow - $LockInfo.LastWriteTimeUtc).TotalMinutes -gt 5
        $OwnerValid = $false
        $OwnerPath = Join-Path $LockPath "pid"
        if (Test-Path -LiteralPath $OwnerPath -PathType Leaf) {
            $OwnerPID = 0
            $OwnerText = (Get-Content -LiteralPath $OwnerPath -Raw -ErrorAction Stop).Trim()
            if ([int]::TryParse($OwnerText, [ref]$OwnerPID)) {
                $OwnerValid = $true
                try {
                    Get-Process -Id $OwnerPID -ErrorAction Stop | Out-Null
                } catch {
                    $Stale = $true
                }
            }
        }
        # Publishing only copies two local files. Expire any old lease so a
        # hung owner or a recycled PID cannot freeze refresh indefinitely.
        if ($Expired) { $Stale = $true }
    } catch {
        return $false
    }
    if (-not $Stale) { return $false }

    # Rename before removal so concurrent reclaimers cannot delete a new lock
    # created at the original path.
    $Reap = "$LockPath.stale.$PID.$([guid]::NewGuid().ToString('N'))"
    try {
        Move-Item -LiteralPath $LockPath -Destination $Reap -ErrorAction Stop
    } catch {
        return $false
    }
    Remove-Item -LiteralPath $Reap -Recurse -Force -ErrorAction SilentlyContinue

    $Created = $false
    try {
        New-Item -ItemType Directory -Path $LockPath -ErrorAction Stop | Out-Null
        $Created = $true
        [System.IO.File]::WriteAllText((Join-Path $LockPath "pid"), "$PID" + [char]10)
        return $true
    } catch {
        if ($Created) {
            Remove-Item -LiteralPath $LockPath -Recurse -Force -ErrorAction SilentlyContinue
        }
        return $false
    }
}

function Save-StablePayload {
    if (-not $env:SPEAKEASY_HOOKS_PERSIST_ROOT) { return $null }

    $ConfigIndex = -1
    $ConfigPath = $env:SPEAKEASY_HOOKS_PERSIST_CONFIG
    for ($Index = 0; $Index -lt $ForwardArgs.Count; $Index++) {
        if ($ForwardArgs[$Index].StartsWith("--config=", [StringComparison]::Ordinal)) {
            $ConfigIndex = $Index
            break
        }
    }
    $ScriptPath = $env:SPEAKEASY_HOOKS_PERSIST_SCRIPT
    if ($ConfigIndex -lt 0 -or
        -not (Test-Path -LiteralPath $ScriptPath -PathType Leaf) -or
        -not (Test-Path -LiteralPath $ConfigPath -PathType Leaf)) { return $null }

    $PersistRoot = $env:SPEAKEASY_HOOKS_PERSIST_ROOT
    $Generations = Join-Path $PersistRoot "generations"
    $Current = Join-Path $PersistRoot ".windows-current"
    $Lock = Join-Path $PersistRoot ".persist-windows.lock"
    $StableScript = $null
    $StableConfig = $null
    try {
        $CurrentGeneration = [System.IO.File]::ReadAllText($Current).Trim()
        if ($CurrentGeneration -and -not ($CurrentGeneration.Contains("/") -or $CurrentGeneration.Contains("\"))) {
            $CurrentDir = Join-Path $Generations $CurrentGeneration
            $CandidateScript = Join-Path $CurrentDir "hooks/bootstrap.ps1"
            $CandidateConfig = Join-Path $CurrentDir "speakeasy.json"
            if ((Test-Path -LiteralPath $CandidateScript -PathType Leaf) -and
                (Test-Path -LiteralPath $CandidateConfig -PathType Leaf)) {
                $StableScript = $CandidateScript
                $StableConfig = $CandidateConfig
                if ((Get-FileHash -LiteralPath $ScriptPath -Algorithm SHA256).Hash -eq
                        (Get-FileHash -LiteralPath $StableScript -Algorithm SHA256).Hash -and
                    (Get-FileHash -LiteralPath $ConfigPath -Algorithm SHA256).Hash -eq
                        (Get-FileHash -LiteralPath $StableConfig -Algorithm SHA256).Hash) {
                    return [PSCustomObject]@{ ConfigIndex = $ConfigIndex; ConfigPath = $StableConfig; ScriptPath = $StableScript; Reexec = $false }
                }
            }
        }
    } catch {}

    $OwnLock = $false
    try {
        New-Item -ItemType Directory -Force -Path $Generations | Out-Null
        if (Enter-PersistenceLock $Lock) {
            $OwnLock = $true
        } else {
            if ((Test-Path -LiteralPath $StableScript -PathType Leaf) -and
                (Test-Path -LiteralPath $StableConfig -PathType Leaf)) {
                return [PSCustomObject]@{ ConfigIndex = $ConfigIndex; ConfigPath = $StableConfig; ScriptPath = $StableScript; Reexec = $false }
            }
            return $null
        }

        $Suffix = [guid]::NewGuid().ToString("N")
        $Generation = "windows-$Suffix"
        $GenerationDir = Join-Path $Generations $Generation
        $HooksDir = Join-Path $GenerationDir "hooks"
        $StableScript = Join-Path $HooksDir "bootstrap.ps1"
        $StableConfig = Join-Path $GenerationDir "speakeasy.json"
        $CurrentTmp = Join-Path $PersistRoot ".windows-current.$Suffix"
        $Published = $false
        try {
            New-Item -ItemType Directory -Force -Path $HooksDir | Out-Null
            Copy-Item -LiteralPath $ScriptPath -Destination $StableScript
            Copy-Item -LiteralPath $ConfigPath -Destination $StableConfig
            [System.IO.File]::WriteAllText($CurrentTmp, $Generation + [char]10)
            Move-Item -LiteralPath $CurrentTmp -Destination $Current -Force
            $Published = $true
            return [PSCustomObject]@{
                ConfigIndex = $ConfigIndex
                ConfigPath = $StableConfig
                ScriptPath = $StableScript
                Reexec = $ScriptPath -ne $PSCommandPath
            }
        } finally {
            Remove-Item -LiteralPath $CurrentTmp -Force -ErrorAction SilentlyContinue
            if (-not $Published) {
                Remove-Item -LiteralPath $GenerationDir -Recurse -Force -ErrorAction SilentlyContinue
            }
        }
    } catch {
        return $null
    } finally {
        if ($OwnLock) {
            Remove-Item -LiteralPath $Lock -Recurse -Force -ErrorAction SilentlyContinue
        }
    }
}

$StablePayload = Save-StablePayload
if ($StablePayload) {
    $ForwardArgs[$StablePayload.ConfigIndex] = "--config=$($StablePayload.ConfigPath)"
    if ($StablePayload.Reexec) {
        Remove-Item Env:SPEAKEASY_HOOKS_PERSIST_ROOT -ErrorAction SilentlyContinue
        Remove-Item Env:SPEAKEASY_HOOKS_PERSIST_SCRIPT -ErrorAction SilentlyContinue
        Remove-Item Env:SPEAKEASY_HOOKS_PERSIST_CONFIG -ErrorAction SilentlyContinue
        & $StablePayload.ScriptPath @ForwardArgs
        exit $LASTEXITCODE
    }
}

$Arch = switch ([System.Runtime.InteropServices.RuntimeInformation]::OSArchitecture.ToString()) {
    "X64" { "amd64" }
    "Arm64" { "arm64" }
    default { "" }
}
if (-not $Arch) { Exit-InstallFailure "unsupported architecture" }
switch ($Arch) {
%s}

if ($env:GRAM_HOOKS_HOME) {
    $CacheRoot = $env:GRAM_HOOKS_HOME
} else {
    $CacheRoot = Join-Path $env:LOCALAPPDATA "Speakeasy/hooks"
}
$InstallDir = Join-Path $CacheRoot "$Version/windows-$Arch"
$Binary = Join-Path $InstallDir "speakeasy-hooks.exe"
$Marker = Join-Path $InstallDir "archive.sha256"
function Test-Cache {
    if (-not (Test-Path -LiteralPath $Binary -PathType Leaf) -or -not (Test-Path -LiteralPath $Marker -PathType Leaf)) { return $false }
    return [System.IO.File]::ReadAllText($Marker).Trim() -eq $ExpectedSha
}
if (Test-Cache) {
    & $Binary @ForwardArgs
    exit $LASTEXITCODE
}

try {
    $null = New-Item -ItemType Directory -Force -Path (Split-Path $InstallDir -Parent)
} catch {
    Exit-InstallFailure "could not create the cache directory"
}
$LockPath = "$InstallDir.lock"
$Waited = 0
while ($true) {
    try {
        New-Item -ItemType Directory -Path $LockPath -ErrorAction Stop | Out-Null
        break
    } catch {
        if (Test-Cache) {
            & $Binary @ForwardArgs
            exit $LASTEXITCODE
        }
        $Stale = $false
        try {
            $Stale = (Get-Item -LiteralPath $LockPath -Force -ErrorAction Stop).LastWriteTimeUtc -lt [DateTime]::UtcNow.AddMinutes(-5)
        } catch {}
        if ($Stale) {
            Remove-Item -LiteralPath $LockPath -Recurse -Force -ErrorAction SilentlyContinue
            continue
        }
        if ($Waited -ge 45) { Exit-InstallFailure "timed out waiting for a concurrent installation" }
        Start-Sleep -Seconds 1
        $Waited++
    }
}

$Work = Join-Path (Split-Path $InstallDir -Parent) (".speakeasy-hooks-" + [guid]::NewGuid())
try {
    if (-not (Test-Cache)) {
        New-Item -ItemType Directory -Force -Path $Work | Out-Null
        $Archive = Join-Path $Work "hooks.zip"
        # -TimeoutSec is not a wall-clock cap on Windows PowerShell 5.1 (it
        # doesn't bound body streaming), so a trickling server could outlive the
        # provider hook budget; run the download in a job and enforce the
        # deadline with Wait-Job.
        $Download = Start-Job -ScriptBlock {
            param($Uri, $OutFile)
            $ProgressPreference = "SilentlyContinue"
            Invoke-WebRequest -UseBasicParsing -TimeoutSec 45 -Uri $Uri -OutFile $OutFile
        } -ArgumentList $Url, $Archive
        try {
            if (-not (Wait-Job -Job $Download -Timeout 45)) {
                Stop-Job -Job $Download
                Exit-InstallFailure "download failed"
            }
            Receive-Job -Job $Download -ErrorAction Stop | Out-Null
        } catch {
            Exit-InstallFailure "download failed"
        } finally {
            Remove-Job -Job $Download -Force -ErrorAction SilentlyContinue
        }
        $ActualSha = (Get-FileHash -Algorithm SHA256 -LiteralPath $Archive).Hash.ToLowerInvariant()
        if ($ActualSha -ne $ExpectedSha) { Exit-InstallFailure "downloaded archive checksum mismatch" }

        $Extracted = Join-Path $Work "extracted"
        Expand-Archive -LiteralPath $Archive -DestinationPath $Extracted
        $Source = Join-Path $Extracted "speakeasy-hooks.exe"
        if (-not (Test-Path -LiteralPath $Source -PathType Leaf)) { Exit-InstallFailure "archive is missing speakeasy-hooks.exe" }
        New-Item -ItemType Directory -Force -Path $InstallDir | Out-Null
        Move-Item -LiteralPath $Source -Destination $Binary -Force
        $MarkerTmp = Join-Path $Work "archive.sha256"
        [System.IO.File]::WriteAllText($MarkerTmp, $ExpectedSha + [char]10)
        Move-Item -LiteralPath $MarkerTmp -Destination $Marker -Force
    }
} catch {
    Exit-InstallFailure $_.Exception.Message
} finally {
    Remove-Item -LiteralPath $LockPath -Recurse -Force -ErrorAction SilentlyContinue
    Remove-Item -LiteralPath $Work -Recurse -Force -ErrorAction SilentlyContinue
}

& $Binary @ForwardArgs
exit $LASTEXITCODE
`, hooksBinaryVersion, conv.Ternary(cfg.InstallFailOpen, 0, 1), hooksDownloadHost(cfg.ServerURL), cases.String())
}

