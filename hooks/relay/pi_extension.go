package relay

import (
	"encoding/json"
	"fmt"
	"strings"
)

// Pi extension packaging. Pi has no hook configuration dialect: the only way
// to observe or gate its agent loop is a TypeScript extension module loaded
// into the Pi process. The generated extension is a thin bridge — it spawns
// the hooks relay and forwards Pi's lifecycle events over the NDJSON frame
// protocol pi.go decodes — so all policy, redaction, and credential handling
// stays in the binary where it is testable and versioned.

// PiExtensionFile is the path of the generated extension within a Pi
// configuration directory. Pi discovers extensions at
// <config>/extensions/<name>/index.ts, where <config> is ~/.pi/agent for all
// projects or a repository's .pi for one project, so a package carrying this
// path installs by extraction into either.
const PiExtensionFile = "extensions/speakeasy-observability/index.ts"

// piServeArgs is the relay invocation the extension spawns. The "pi" sentinel
// must lead: the binary dispatches subcommands on the first argument, and the
// deployment identity rides in --config rather than argv values.
var piServeArgs = []string{"pi", "serve"}

// RenderPiExtensionForBinary renders the Pi extension for a package whose
// hooks binary is already on disk at a known path. It backs local installs
// and end-to-end tests, where no download bootstrap is involved.
func RenderPiExtensionForBinary(binaryPath, configPath string) ([]byte, error) {
	argv := append([]string{binaryPath}, piServeArgs...)
	argv = append(argv, "--config="+configPath)
	command, err := json.Marshal(argv)
	if err != nil {
		return nil, fmt.Errorf("marshal pi extension command: %w", err)
	}
	return renderPiExtension("const COMMAND: string[] = " + string(command)), nil
}

// RenderPiExtensionForBootstrap renders the Pi extension for a distributed
// package: every path resolves relative to the extension's own location, so
// one file works from a global ~/.pi/agent or a repository .pi, and the
// relay is launched through the package's pinned-binary bootstrap script.
func RenderPiExtensionForBootstrap() []byte {
	serveArgs, err := json.Marshal(piServeArgs)
	if err != nil {
		// piServeArgs is a package-level literal of plain strings, so this
		// cannot fail; the assignment keeps the template honest if it ever
		// gains a non-marshalable value.
		serveArgs = []byte(`["pi","serve"]`)
	}
	command := fmt.Sprintf(`const SERVE_ARGS: string[] = [...%s, "--config=" + join(ROOT, "speakeasy.json")]
// The bootstrap script downloads and checksum-verifies the pinned relay
// binary, then execs it with these arguments. Pi runs the extension in its
// own Node process, so the platform switch lives here rather than in a
// provider config field.
const COMMAND: string[] =
  process.platform === "win32"
    ? ["powershell.exe", "-NoLogo", "-NoProfile", "-ExecutionPolicy", "Bypass", "-File", join(ROOT, "hooks", "bootstrap.ps1"), ...SERVE_ARGS]
    : ["bash", join(ROOT, "hooks", "bootstrap.sh"), ...SERVE_ARGS]`, string(serveArgs))
	return renderPiExtension(command)
}

func renderPiExtension(command string) []byte {
	return []byte(strings.Replace(piExtensionTemplate, piExtensionCommandMarker, command, 1))
}

const piExtensionCommandMarker = "//__SPEAKEASY_COMMAND__"

// piExtensionTemplate is the generated Pi extension. It carries no
// org-specific values: the deployment identity rides in the sibling
// speakeasy.json that --config points at.
//
// Every handler is wrapped so a relay or protocol failure degrades to "no
// telemetry" instead of breaking the user's agent, and every request is
// bounded by a timeout Pi does not impose on extension handlers. The relay
// still gates independently: a frame that never gets a reply is an allow
// here, while the binary's own credential ratchet and the organization's
// fail-open posture decide what happens to events it cannot deliver.
const piExtensionTemplate = `// Generated by Speakeasy. Bridges the Pi extension API to the Speakeasy hooks
// relay over NDJSON stdio (speakeasy-hooks pi serve).
import { spawn, type ChildProcess } from "node:child_process"
import { createInterface } from "node:readline"
import { fileURLToPath } from "node:url"
import { dirname, join } from "node:path"

// Pi loads extensions through jiti, which may evaluate this module as either
// ESM or CJS; one of the two directory sources is always defined.
declare const __dirname: string | undefined
const HERE = typeof __dirname === "string" ? __dirname : dirname(fileURLToPath(import.meta.url))
// Pi discovers this file at <config>/extensions/<name>/index.ts, so the
// package root is two levels up.
const ROOT = join(HERE, "..", "..")
//__SPEAKEASY_COMMAND__
const HOOK_TIMEOUT_MS = 30_000
// Tool output and assistant text are reported for observability, not replay.
// The cap bounds one frame; the relay redacts and the server stores what it
// receives.
const MAX_TEXT_BYTES = 32_000
// The relay drops any line over 8 MiB without a reply, so frames stay well
// under it. A larger one is sent as its identifying fields only, flagged
// oversized, and the relay blocks it if it is a gate.
const MAX_FRAME_BYTES = 4_000_000

type Reply = { block?: boolean; reason?: string }

// Cuts text to at most maxBytes of UTF-8 without splitting a character. Every
// UTF-16 code unit encodes to at least one byte, so slicing first bounds the
// encode.
const truncateUtf8 = (text: string, maxBytes: number): string => {
  if (maxBytes <= 0) return ""
  const bytes = Buffer.from(text.slice(0, maxBytes), "utf8")
  if (bytes.length <= maxBytes) return bytes.toString("utf8")
  let end = maxBytes
  while (end > 0 && (bytes[end] & 0xc0) === 0x80) end--
  return bytes.subarray(0, end).toString("utf8")
}

// Each block is truncated before it is joined, so an oversized tool result is
// never copied whole.
const textOf = (content: unknown): string => {
  const texts: string[] = []
  if (typeof content === "string") texts.push(content)
  else if (Array.isArray(content)) {
    for (const block of content) {
      if (block && typeof block === "object" && (block as any).type === "text" && typeof (block as any).text === "string") {
        texts.push((block as any).text)
      }
    }
  }
  let out = ""
  let used = 0
  for (const text of texts) {
    const room = MAX_TEXT_BYTES - used - (out ? 1 : 0)
    if (room <= 0) break
    const piece = (out ? "\n" : "") + truncateUtf8(text, room)
    out += piece
    used += Buffer.byteLength(piece, "utf8")
  }
  return out
}

const usageOf = (usage: any): Record<string, unknown> | null => {
  if (!usage || typeof usage !== "object") return null
  return {
    input: usage.input ?? null,
    output: usage.output ?? null,
    cache_read: usage.cacheRead ?? null,
    cache_write: usage.cacheWrite ?? null,
    cost: usage.cost?.total ?? null,
  }
}

export default function (pi: any) {
  let child: ChildProcess | undefined
  let stopped = false
  let seq = 0
  let turnIndex = 0
  const pending = new Map<number, (reply: Reply) => void>()

  const failPending = () => {
    for (const [, resolve] of pending) resolve({})
    pending.clear()
  }

  // Pi may load extensions in invocations that never start a session, so the
  // relay is spawned on the first event rather than in this factory.
  const relay = (): ChildProcess | undefined => {
    if (stopped) return undefined
    if (child) return child
    let proc: ChildProcess
    try {
      proc = spawn(COMMAND[0], COMMAND.slice(1), { stdio: ["pipe", "pipe", "inherit"] })
    } catch {
      stopped = true
      return undefined
    }
    child = proc
    // A relay that has since been replaced must not fail the requests of the
    // one that replaced it.
    proc.on("error", () => {
      if (child !== proc) return
      stopped = true
      failPending()
    })
    proc.on("exit", () => {
      if (child === proc) failPending()
    })
    if (proc.stdout) {
      createInterface({ input: proc.stdout }).on("line", (line: string) => {
        if (!line.trim()) return
        let reply: any
        try {
          reply = JSON.parse(line)
        } catch {
          return
        }
        const resolve = pending.get(reply?.seq)
        if (!resolve) return
        pending.delete(reply.seq)
        resolve(reply as Reply)
      })
    }
    return proc
  }

  // The relay answers frames strictly in order, so one that missed its
  // deadline would hold every later frame behind it. Retire it; the next event
  // spawns a fresh relay.
  const replace = (proc: ChildProcess) => {
    if (child !== proc) return
    child = undefined
    failPending()
    try {
      proc.stdin?.end()
      proc.kill()
    } catch {}
  }

  const session = (ctx: any): Record<string, string> => {
    let id = ""
    try {
      id = ctx?.sessionManager?.getSessionId?.() ?? ""
    } catch {}
    return {
      id: typeof id === "string" ? id : "",
      turn_id: turnIndex > 0 ? "turn-" + turnIndex : "",
      cwd: typeof ctx?.cwd === "string" ? ctx.cwd : "",
      model: ctx?.model?.id ?? ctx?.model?.model ?? "",
    }
  }

  const call = (hook: string, ctx: any, input: unknown): Promise<Reply> => {
    const proc = relay()
    if (!proc || proc.exitCode !== null || !proc.stdin?.writable) return Promise.resolve({})
    const id = ++seq
    try {
      let line = JSON.stringify({ seq: id, hook, session: session(ctx), input })
      if (Buffer.byteLength(line, "utf8") > MAX_FRAME_BYTES) {
        const fields = (input ?? {}) as any
        line = JSON.stringify({
          seq: id,
          hook,
          session: session(ctx),
          oversized: true,
          input: { tool_call_id: fields.tool_call_id ?? "", tool_name: fields.tool_name ?? "" },
        })
      }
      proc.stdin.write(line + "\n")
    } catch {
      return Promise.resolve({})
    }
    return new Promise<Reply>((resolve) => {
      pending.set(id, resolve)
      const timer = setTimeout(() => {
        if (!pending.delete(id)) return
        resolve({})
        replace(proc)
      }, HOOK_TIMEOUT_MS)
      // A pending hook reply must not hold the process open.
      if (typeof timer.unref === "function") timer.unref()
    })
  }

  const dispose = () => {
    stopped = true
    failPending()
    try {
      child?.stdin?.end()
      child?.kill()
    } catch {}
    child = undefined
  }

  pi.on("session_start", async (event: any, ctx: any) => {
    turnIndex = 0
    stopped = false
    await call("session_start", ctx, { reason: event?.reason ?? "" })
  })

  pi.on("session_shutdown", async (event: any, ctx: any) => {
    await call("session_shutdown", ctx, { reason: event?.reason ?? "" })
    dispose()
  })

  pi.on("turn_start", (event: any) => {
    const index = event?.turnIndex
    turnIndex = typeof index === "number" ? index + 1 : turnIndex + 1
  })

  pi.on("input", async (event: any, ctx: any) => {
    // Extension-injected input is this integration's own notices and other
    // extensions' synthesized messages, not something a user submitted.
    if (event?.source === "extension") return { action: "continue" }
    const reply = await call("input", ctx, {
      text: typeof event?.text === "string" ? event.text : "",
      source: event?.source ?? "",
    })
    if (!reply?.block) return { action: "continue" }
    const reason = reply.reason || "Speakeasy blocked this prompt."
    try {
      ctx?.ui?.notify?.(reason, "error")
    } catch {}
    // "handled" is Pi's only way to keep a prompt out of the agent loop.
    return { action: "handled" }
  })

  pi.on("tool_call", async (event: any, ctx: any) => {
    const reply = await call("tool_call", ctx, {
      tool_call_id: event?.toolCallId ?? "",
      tool_name: event?.toolName ?? "",
      input: event?.input ?? {},
    })
    if (!reply?.block) return
    return { block: true, reason: reply.reason || "Speakeasy blocked this tool call." }
  })

  pi.on("tool_result", async (event: any, ctx: any) => {
    await call("tool_result", ctx, {
      tool_call_id: event?.toolCallId ?? "",
      tool_name: event?.toolName ?? "",
      input: event?.input ?? {},
      output: textOf(event?.content),
      is_error: event?.isError === true,
    })
  })

  pi.on("message_end", async (event: any, ctx: any) => {
    const message = event?.message
    if (message?.role !== "assistant") return
    await call("message_end", ctx, {
      text: textOf(message.content),
      stop_reason: message.stopReason ?? "",
      usage: usageOf(message.usage),
    })
  })
}
`
