// Package ignore reads and writes the sqlclint ignore file.
//
// The file carries two kinds of entry. Path globs exclude files from checking
// permanently. Query entries grandfather a known violation, and each is pinned
// to a hash of the query body it was recorded against, which is what makes the
// file a ratchet: editing a grandfathered query invalidates its entry and the
// violation is reported again.
package ignore

import (
	"bufio"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path"
	"slices"
	"strings"
)

// Entry is one grandfathered query.
type Entry struct {
	// Ref is "<file>::<QueryName>".
	Ref string

	// Hash fingerprints the query body the entry was recorded against.
	Hash string
}

// File is a parsed ignore file.
type File struct {
	// Globs are path patterns excluded from checking entirely.
	Globs []string

	// Entries are grandfathered queries, keyed by Ref.
	Entries map[string]Entry
}

// Load reads an ignore file. A missing file is an empty one, so a first run
// needs no setup.
func Load(filename string) (*File, error) {
	f := &File{Globs: nil, Entries: map[string]Entry{}}

	fh, err := os.Open(filename)
	if errors.Is(err, fs.ErrNotExist) {
		return f, nil
	}
	if err != nil {
		return nil, fmt.Errorf("open ignore file: %w", err)
	}
	defer func() { _ = fh.Close() }()

	scanner := bufio.NewScanner(fh)
	for line := 1; scanner.Scan(); line++ {
		text := strings.TrimSpace(scanner.Text())
		if text == "" || strings.HasPrefix(text, "#") {
			continue
		}

		ref, hash, hasHash := strings.Cut(text, " ")
		if !hasHash {
			f.Globs = append(f.Globs, text)
			continue
		}

		hash = strings.TrimSpace(hash)
		if !strings.Contains(ref, "::") {
			return nil, fmt.Errorf("%s:%d: %q has a hash but is not a <file>::<Query> reference", filename, line, ref)
		}
		f.Entries[ref] = Entry{Ref: ref, Hash: hash}
	}
	if err := scanner.Err(); err != nil {
		return nil, fmt.Errorf("read ignore file: %w", err)
	}

	return f, nil
}

// Skipped reports whether a file path is excluded by a glob.
func (f *File) Skipped(filename string) bool {
	for _, g := range f.Globs {
		if matchGlob(g, filename) {
			return true
		}
	}
	return false
}

// Lookup returns the grandfathered entry for a query reference.
func (f *File) Lookup(ref string) (Entry, bool) {
	e, ok := f.Entries[ref]
	return e, ok
}

// Save writes an ignore file, preserving the given globs and sorting entries so
// the file has a stable diff.
func Save(filename string, globs []string, entries []Entry) error {
	var b strings.Builder

	b.WriteString("# Generated by `sqlclint run --write-ignore-file`.\n")
	b.WriteString("#\n")
	b.WriteString("# Bare paths are globs excluded from checking entirely.\n")
	b.WriteString("#\n")
	b.WriteString("# Lines with a hash are grandfathered violations: known debt, not approved\n")
	b.WriteString("# exemptions. The hash pins the entry to the query body it was recorded\n")
	b.WriteString("# against, so editing the query re-raises the violation. To clear an entry,\n")
	b.WriteString("# scope the query, or annotate it with `-- sqlclint:ignore <category> -- <why>`\n")
	b.WriteString("# and regenerate. Do not add or edit these lines by hand.\n")

	if len(globs) > 0 {
		b.WriteString("\n")
		for _, g := range globs {
			b.WriteString(g)
			b.WriteString("\n")
		}
	}

	sorted := slices.Clone(entries)
	slices.SortFunc(sorted, func(a, c Entry) int { return strings.Compare(a.Ref, c.Ref) })

	if len(sorted) > 0 {
		b.WriteString("\n")
		for _, e := range sorted {
			fmt.Fprintf(&b, "%s %s\n", e.Ref, e.Hash)
		}
	}

	if err := os.WriteFile(filename, []byte(b.String()), 0o644); err != nil {
		return fmt.Errorf("write ignore file: %w", err)
	}
	return nil
}

// matchGlob matches a slash-separated path against a pattern where "**" spans
// any number of segments and every other segment follows path.Match.
func matchGlob(pattern, name string) bool {
	return matchSegments(strings.Split(pattern, "/"), strings.Split(name, "/"))
}

func matchSegments(pattern, name []string) bool {
	for len(pattern) > 0 {
		if pattern[0] == "**" {
			// Zero segments, or one segment consumed and retry.
			if matchSegments(pattern[1:], name) {
				return true
			}
			if len(name) == 0 {
				return false
			}
			name = name[1:]
			continue
		}

		if len(name) == 0 {
			return false
		}
		if ok, err := path.Match(pattern[0], name[0]); err != nil || !ok {
			return false
		}
		pattern, name = pattern[1:], name[1:]
	}

	return len(name) == 0
}
