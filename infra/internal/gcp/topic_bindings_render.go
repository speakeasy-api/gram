// topicsTemplate renders the statically typed topic registry.
//
// The generated switch is the point of the whole file: every arm binds a topic
// name to a concrete Go type at compile time, so a topic can be named by a
// string on an outbox row without the publish path ever losing type safety.
var topicsTemplate = template.Must(template.New("topics").Parse(`// Code generated by infra gen-topics. DO NOT EDIT.

package topics

import (
	"context"
	"fmt"

	"cloud.google.com/go/pubsub/v2"

	"github.com/speakeasy-api/gram/infra/pkg/gcp"
{{- range .Imports }}
	{{ .Alias }} "{{ .Path }}"
{{- end }}
)

// Topic identifies a protobuf message that declares a Pub/Sub topic.
//
// Values are generated from the descriptor set, so referring to a topic that
// does not exist is a compile error rather than a runtime lookup failure.
type Topic string

const (
{{- range .Bindings }}
	// {{ .ConstName }} publishes to {{ .TopicID }}.
	{{ .ConstName }} Topic = "{{ .ProtoFullName }}"
{{- end }}
)

// All returns every declared topic, sorted by proto name.
func All() []Topic {
	return []Topic{
{{- range .Bindings }}
		{{ .ConstName }},
{{- end }}
	}
}

// Lookup reports whether name is a declared topic.
func Lookup(name string) (Topic, bool) {
	switch Topic(name) {
{{- range .Bindings }}
	case {{ .ConstName }}:
		return {{ .ConstName }}, true
{{- end }}
	default:
		return "", false
	}
}

// newPublisher builds a byte-carrying publisher for a topic. Each arm names
// the topic's generated Go type, which is the only way the gcp package lets a
// topic be addressed — so the runtime name-to-type hop happens here, at
// compile time, and payloads pass through to the topic untouched.
func newPublisher(ctx context.Context, broker gcp.PublisherBroker, topic Topic, settings *pubsub.PublishSettings) (gcp.EncodedPublisher, error) {
	switch topic {
{{- range .Bindings }}
	case {{ .ConstName }}:
		return gcp.PubSubEncodedPublisherForMessage(ctx, broker, &{{ .GoPackageAlias }}.{{ .GoTypeName }}{}, gcp.WithEncodedPublishSettings(settings))
{{- end }}
	default:
		return nil, fmt.Errorf("%w: %s", ErrUnknownTopic, topic)
	}
}
`))

type topicsTemplateImport struct {
	Alias string
	Path  string
}

type topicsTemplateData struct {
	Imports  []topicsTemplateImport
	Bindings []TopicBinding
}

// RenderTopics generates the typed topic registry from a descriptor set.
func RenderTopics(descriptorBytes []byte) ([]byte, error) {
	bindings, err := DiscoverTopicBindings(descriptorBytes)
	if err != nil {
		return nil, fmt.Errorf("discover topic bindings: %w", err)
	}

	data, err := buildTopicsTemplateData(bindings)
	if err != nil {
		return nil, err
	}

	var buf bytes.Buffer
	if err := topicsTemplate.Execute(&buf, data); err != nil {
		return nil, fmt.Errorf("render topics template: %w", err)
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated topics: %w", err)
	}

	return formatted, nil
}

// buildTopicsTemplateData assigns one import alias per package, disambiguating
// collisions so two packages that prefer the same identifier can coexist.
func buildTopicsTemplateData(bindings []TopicBinding) (topicsTemplateData, error) {
	aliasByPath := map[string]string{}
	// Seeded with every identifier the template itself declares — its fixed
	// imports and its own package name. A topic package that prefers one of
	// these would otherwise shadow it: duplicate import names are valid syntax,
	// so format.Source would pass and the break would only surface as a
	// repo-wide compile error in the generated file. The empty owner can never
	// equal an import path, so these entries always force a suffix.
	takenAliases := map[string]string{
		"context": "",
		"fmt":     "",
		"pubsub":  "",
		"gcp":     "",
		"topics":  "",
	}

	paths := make([]string, 0, len(bindings))
	for _, binding := range bindings {
		if _, seen := aliasByPath[binding.GoImportPath]; seen {
			continue
		}
		paths = append(paths, binding.GoImportPath)
		aliasByPath[binding.GoImportPath] = binding.GoPackageAlias
	}
	sort.Strings(paths)

	for _, importPath := range paths {
		alias := aliasByPath[importPath]
		if alias == "" {
			return topicsTemplateData{}, fmt.Errorf("import path %q has no package alias", importPath)
		}

		candidate := alias
		for suffix := 2; ; suffix++ {
			owner, taken := takenAliases[candidate]
			if !taken || owner == importPath {
				break
			}
			candidate = fmt.Sprintf("%s%d", alias, suffix)
		}

		takenAliases[candidate] = importPath
		aliasByPath[importPath] = candidate
	}

	imports := make([]topicsTemplateImport, 0, len(paths))
	for _, importPath := range paths {
		imports = append(imports, topicsTemplateImport{Alias: aliasByPath[importPath], Path: importPath})
	}

	resolved := make([]TopicBinding, 0, len(bindings))
	for _, binding := range bindings {
		binding.GoPackageAlias = aliasByPath[binding.GoImportPath]
		resolved = append(resolved, binding)
	}

	return topicsTemplateData{Imports: imports, Bindings: resolved}, nil
}

// WriteTopics renders the registry and writes it to out.
func WriteTopics(descriptorBytes []byte, out string) error {
	rendered, err := RenderTopics(descriptorBytes)
	if err != nil {
		return err
	}

	if err := os.MkdirAll(filepath.Dir(out), 0o750); err != nil {
		return fmt.Errorf("create output directory: %w", err)
	}

	if err := os.WriteFile(out, rendered, 0o600); err != nil {
		return fmt.Errorf("write generated topics: %w", err)
	}

	return nil
}

// CheckTopics reports whether the file at out matches what would be generated,
// so CI can fail on drift instead of shipping a stale registry.
func CheckTopics(descriptorBytes []byte, out string) error {
	rendered, err := RenderTopics(descriptorBytes)
	if err != nil {
		return err
	}

	existing, err := os.ReadFile(out) // #nosec G304 - path is operator supplied
	if err != nil {
		return fmt.Errorf("read %s: %w", out, err)
	}

	if !bytes.Equal(bytes.TrimSpace(existing), bytes.TrimSpace(rendered)) {
		return fmt.Errorf("%s is out of date; run: mise run gen:infra", strings.TrimSpace(out))
	}

	return nil
}
