package gcp

import (
	"bytes"
	"cmp"
	"crypto/sha256"
	"encoding/json"
	"fmt"
	"slices"
	"strconv"
	"strings"

	"github.com/parquet-go/parquet-go"
	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/descriptorpb"
	"google.golang.org/protobuf/types/pluginpb"
)

const (
	// StorageMappingVersion identifies the frozen protobuf-to-Parquet mapping
	// contract used by generated manifests, fingerprints and object metadata.
	StorageMappingVersion = "1"

	// maxStorageDepth leaves room for LIST/MAP levels within Parquet's limit.
	maxStorageDepth = 40

	// maxStorageColumns bounds code expansion for shared, acyclic message graphs.
	maxStorageColumns = 4096
)

type storageNode struct {
	name     string
	kind     string
	field    *protogen.Field
	oneof    *protogen.Oneof
	optional bool
	children []*storageNode
	column   int
	end      int
}

type storageManifest struct {
	// MappingVersion freezes presence, collections and generated column semantics.
	MappingVersion string `json:"mapping_version"`

	// Subscriptions is sorted by marker's fully qualified proto name.
	Subscriptions []storageManifestEntry `json:"subscriptions"`
}

type storageManifestEntry struct {
	// Marker identifies the storage prefix independently of a transport override.
	Marker string `json:"marker"`

	// Payload identifies the protobuf topic payload.
	Payload string `json:"payload"`

	// Fingerprint covers schema and protobuf field numbers, not source comments.
	Fingerprint string `json:"fingerprint"`

	// Schema is an independent, readable physical/logical schema listing.
	Schema string `json:"schema"`

	// Fields records source numbers and kinds for compatibility review.
	Fields []string `json:"fields"`
}

// RenderStorage generates explicit schemas, typed encoders and a review manifest.
// The caller validates actual schema attachment against the source proto files.
func RenderStorage(raw []byte, packageName, importPath string) ([]byte, []byte, error) {
	_, subs, err := DiscoverPubSub(raw)
	if err != nil {
		return nil, nil, err
	}
	var set descriptorpb.FileDescriptorSet
	if err := proto.Unmarshal(raw, &set); err != nil {
		return nil, nil, fmt.Errorf("decode descriptors: %w", err)
	}
	if len(set.File) == 0 {
		return nil, nil, fmt.Errorf("storage descriptors contain no files")
	}
	plugin, err := (protogen.Options{}).New(&pluginpb.CodeGeneratorRequest{ProtoFile: set.File})
	if err != nil {
		return nil, nil, fmt.Errorf("resolve generated Go names: %w", err)
	}
	messages := map[string]*protogen.Message{}
	var walk func([]*protogen.Message)
	walk = func(ms []*protogen.Message) {
		for _, m := range ms {
			messages[string(m.Desc.FullName())] = m
			walk(m.Messages)
		}
	}
	for _, file := range plugin.Files {
		walk(file.Messages)
	}
	g := plugin.NewGeneratedFile("storage_gen.go", protogen.GoImportPath(importPath))
	g.P("// Code generated by infra gen-storage. DO NOT EDIT.")
	g.P("package ", packageName)
	q := func(path, name string) string {
		return g.QualifiedGoIdent(protogen.GoIdent{GoImportPath: protogen.GoImportPath(path), GoName: name})
	}
	storage := func(name string) string { return q("github.com/speakeasy-api/gram/infra/pkg/storage", name) }
	pq := func(name string) string { return q("github.com/parquet-go/parquet-go", name) }
	manifest := storageManifest{MappingVersion: StorageMappingVersion, Subscriptions: []storageManifestEntry{}}
	slices.SortFunc(subs, func(a, b DesiredSubscription) int { return cmp.Compare(a.ProtoMessage, b.ProtoMessage) })
	names := map[string]string{}
	for _, sub := range subs {
		if sub.Storage == nil {
			continue
		}
		payload, marker := messages[sub.TopicMessage], messages[sub.ProtoMessage]
		if payload == nil {
			return nil, nil, fmt.Errorf("storage payload %s is missing from descriptors", sub.TopicMessage)
		}
		if marker == nil {
			return nil, nil, fmt.Errorf("storage marker %s is missing from descriptors", sub.ProtoMessage)
		}
		name := constNameFor(protoreflect.FullName(sub.ProtoMessage))
		if previous, exists := names[name]; exists {
			return nil, nil, fmt.Errorf("storage Go name %s collides: %s and %s", name, previous, sub.ProtoMessage)
		}
		names[name] = sub.ProtoMessage
		// Bound expansion before building the tree: an acyclic shared descriptor
		// can still expand exponentially when represented as nested columns.
		budget := 4 * maxStorageColumns
		root, err := storageMessageNode(payload, false, 0, &budget)
		if err != nil {
			return nil, nil, fmt.Errorf("storage subscription %s: %w", sub.ProtoMessage, err)
		}
		root.children = append(root.children, &storageNode{name: "__pubsub", kind: "metadata", children: []*storageNode{
			{name: "message_id", kind: "metadata_id"}, {name: "received_micros", kind: "metadata_time"}, {name: "topic", kind: "metadata_topic"},
		}})
		slices.SortFunc(root.children, func(a, b *storageNode) int { return cmp.Compare(a.name, b.name) })
		column := 0
		assignStorageColumns(root, &column)
		if column > maxStorageColumns {
			return nil, nil, fmt.Errorf("storage subscription %s expands to %d columns (limit %d)", sub.ProtoMessage, column, maxStorageColumns)
		}
		schema := parquet.NewSchema(sub.TopicMessage, root.schema())
		entry := storageManifestEntry{Marker: sub.ProtoMessage, Payload: sub.TopicMessage, Schema: schema.String(), Fields: []string{}}
		root.collectFields("", &entry.Fields)
		hash := sha256.Sum256([]byte("mapping=" + manifest.MappingVersion + "\n" + entry.Schema + "\n" + strings.Join(entry.Fields, "\n")))
		entry.Fingerprint = fmt.Sprintf("%x", hash)
		manifest.Subscriptions = append(manifest.Subscriptions, entry)
		g.P("var schema", name, " = ", pq("NewSchema"), "(", strconv.Quote(sub.TopicMessage), ",", root.schemaCode(pq), ")")
		g.P("// ", name, " returns the generated storage binding for ", sub.ProtoMessage, ".")
		g.P("func ", name, "() ", storage("Definition"), " { return ", storage("Definition"), "{")
		g.P("Marker: &", g.QualifiedGoIdent(marker.GoIdent), "{}, Payload: &", g.QualifiedGoIdent(payload.GoIdent), "{},")
		g.P("ProtoName: ", strconv.Quote(sub.ProtoMessage), ", SubscriptionID: ", strconv.Quote(sub.Name), ", TopicID: ", strconv.Quote(sub.Topic), ", Bucket: ", strconv.Quote(sub.Storage.Bucket), ",")
		g.P("Partitioning: ", q("github.com/speakeasy-api/gram/infra/gen/gcp/pubsub/v1", "StoragePartitioning_"+sub.Storage.Partitioning.String()), ",")
		g.P("PartitionAttribute: ", strconv.Quote(sub.Storage.PartitionAttribute), ", PartitionKeys: []string{")
		for _, key := range sub.Storage.PartitionKeys {
			g.P(strconv.Quote(key), ",")
		}
		g.P("}, Schema: schema", name, ", Fingerprint: ", strconv.Quote(entry.Fingerprint), ",")
		g.P("Decode: func(data []byte, meta ", storage("Metadata"), ") (", pq("Row"), ", error) {")
		g.P("m := &", g.QualifiedGoIdent(payload.GoIdent), "{}")
		g.P("if err := ", q("google.golang.org/protobuf/proto", "Unmarshal"), "(data, m); err != nil { return nil, ", q("fmt", "Errorf"), "(\"decode storage payload: %w\", err) }")
		g.P("return Encode", name, "(m, meta), nil }, }}")
		g.P("// Encode", name, " maps typed protobuf accessors to explicit Parquet levels.")
		g.P("func Encode", name, "(m *", g.QualifiedGoIdent(payload.GoIdent), ", meta ", storage("Metadata"), ") ", pq("Row"), " {")
		g.P("var columns [", column, "][]", pq("Value"))
		emitter := storageEmitter{g: g, pq: pq, q: q, topic: sub.Topic}
		emitter.emit(root, "m", "0", 0, 0)
		g.P("return ", pq("MakeRow"), "(columns[:]...) }")
	}
	content, err := g.Content()
	if err != nil {
		return nil, nil, fmt.Errorf("format storage encoders: %w", err)
	}
	manifestBytes, err := json.MarshalIndent(manifest, "", "  ")
	if err != nil {
		return nil, nil, fmt.Errorf("marshal storage manifest: %w", err)
	}
	return content, append(manifestBytes, '\n'), nil
}

func storageMessageNode(m *protogen.Message, witness bool, depth int, budget *int) (*storageNode, error) {
	if depth > maxStorageDepth {
		return nil, fmt.Errorf("payload %s exceeds nesting limit %d", m.Desc.FullName(), maxStorageDepth)
	}
	n := &storageNode{kind: "message"}
	if witness {
		n.children = append(n.children, &storageNode{name: "__present", kind: "witness"})
	}
	seen := map[string]bool{}
	for _, f := range m.Fields {
		name := string(f.Desc.Name())
		lower := strings.ToLower(name)
		if strings.HasPrefix(lower, "__") || strings.HasPrefix(lower, "part__") || seen[lower] {
			return nil, fmt.Errorf("payload column %s is reserved or collides case-insensitively", f.Desc.FullName())
		}
		seen[lower] = true
		child, err := storageFieldNode(f, depth+1, budget)
		if err != nil {
			return nil, err
		}
		child.name, child.field = name, f
		child.optional = f.Desc.HasPresence() && !f.Desc.IsList() && !f.Desc.IsMap()
		n.children = append(n.children, child)
	}
	for _, o := range m.Oneofs {
		if !o.Desc.IsSynthetic() {
			n.children = append(n.children, &storageNode{name: "__oneof_" + string(o.Desc.Name()), kind: "oneof", oneof: o, optional: true})
		}
	}
	slices.SortFunc(n.children, func(a, b *storageNode) int { return cmp.Compare(a.name, b.name) })
	return n, nil
}

func storageFieldNode(f *protogen.Field, depth int, budget *int) (*storageNode, error) {
	if f.Desc.IsMap() {
		key, err := storageValueNode(f.Message.Fields[0], depth, budget)
		if err != nil {
			return nil, err
		}
		value, err := storageValueNode(f.Message.Fields[1], depth, budget)
		if err != nil {
			return nil, err
		}
		key.name, value.name = "key", "value"
		return &storageNode{kind: "map", children: []*storageNode{key, value}}, nil
	}
	value, err := storageValueNode(f, depth, budget)
	if err != nil {
		return nil, err
	}
	if f.Desc.IsList() {
		return &storageNode{kind: "list", children: []*storageNode{value}}, nil
	}
	return value, nil
}

func storageValueNode(f *protogen.Field, depth int, budget *int) (*storageNode, error) {
	*budget--
	if *budget < 0 {
		return nil, fmt.Errorf("payload expansion exceeds storage schema complexity limit at %s", f.Desc.FullName())
	}
	if f.Message != nil {
		return storageMessageNode(f.Message, true, depth, budget)
	}
	return &storageNode{kind: f.Desc.Kind().String()}, nil
}

func assignStorageColumns(n *storageNode, col *int) {
	n.column = *col
	if len(n.children) == 0 {
		*col++
	} else {
		for _, child := range n.children {
			assignStorageColumns(child, col)
		}
	}
	n.end = *col
}

func (n *storageNode) collectFields(path string, fields *[]string) {
	if n.name != "" {
		path += "." + n.name
	}
	if n.field != nil {
		oneof := ""
		if n.field.Oneof != nil && !n.field.Oneof.Desc.IsSynthetic() {
			oneof = ", oneof=" + string(n.field.Oneof.Desc.Name())
		}
		*fields = append(*fields, fmt.Sprintf("%s = %d (%s, presence=%t%s)", path, n.field.Desc.Number(), n.field.Desc.Kind(), n.field.Desc.HasPresence(), oneof))
	}
	for _, child := range n.children {
		child.collectFields(path, fields)
	}
}

func (n *storageNode) schema() parquet.Node {
	var result parquet.Node
	switch n.kind {
	case "message", "metadata":
		group := parquet.Group{}
		for _, child := range n.children {
			group[child.name] = child.schema()
		}
		result = group
	case "list":
		result = parquet.List(n.children[0].schema())
	case "map":
		result = parquet.Map(n.children[0].schema(), n.children[1].schema())
	case "bool", "witness":
		result = parquet.Leaf(parquet.BooleanType)
	case "int32", "sint32", "sfixed32", "enum", "oneof":
		result = parquet.Int(32)
	case "int64", "sint64", "sfixed64", "metadata_time":
		result = parquet.Int(64)
	case "uint32", "fixed32":
		result = parquet.Uint(32)
	case "uint64", "fixed64":
		result = parquet.Uint(64)
	case "float":
		result = parquet.Leaf(parquet.FloatType)
	case "double":
		result = parquet.Leaf(parquet.DoubleType)
	case "bytes":
		result = parquet.Leaf(parquet.ByteArrayType)
	case "string", "metadata_id", "metadata_topic":
		result = parquet.String()
	default:
		panic("unsupported storage kind " + n.kind)
	}
	if n.optional {
		result = parquet.Optional(result)
	}
	return result
}

func (n *storageNode) schemaCode(pq func(string) string) string {
	var result string
	switch n.kind {
	case "message", "metadata":
		var b bytes.Buffer
		b.WriteString(pq("Group") + "{\n")
		for _, child := range n.children {
			fmt.Fprintf(&b, "%q: %s,\n", child.name, child.schemaCode(pq))
		}
		b.WriteString("}")
		result = b.String()
	case "list":
		result = pq("List") + "(" + n.children[0].schemaCode(pq) + ")"
	case "map":
		result = pq("Map") + "(" + n.children[0].schemaCode(pq) + ", " + n.children[1].schemaCode(pq) + ")"
	case "bool", "witness":
		result = pq("Leaf") + "(" + pq("BooleanType") + ")"
	case "int32", "sint32", "sfixed32", "enum", "oneof":
		result = pq("Int") + "(32)"
	case "int64", "sint64", "sfixed64", "metadata_time":
		result = pq("Int") + "(64)"
	case "uint32", "fixed32":
		result = pq("Uint") + "(32)"
	case "uint64", "fixed64":
		result = pq("Uint") + "(64)"
	case "float":
		result = pq("Leaf") + "(" + pq("FloatType") + ")"
	case "double":
		result = pq("Leaf") + "(" + pq("DoubleType") + ")"
	case "bytes":
		result = pq("Leaf") + "(" + pq("ByteArrayType") + ")"
	case "string", "metadata_id", "metadata_topic":
		result = pq("String") + "()"
	default:
		panic("unsupported storage kind " + n.kind)
	}
	if n.optional {
		result = pq("Optional") + "(" + result + ")"
	}
	return result
}

type storageEmitter struct {
	g     *protogen.GeneratedFile
	pq    func(string) string
	q     func(string, string) string
	topic string
	next  int
}

func (e *storageEmitter) variable(prefix string) string {
	e.next++
	return fmt.Sprintf("%s%d", prefix, e.next)
}

func (e *storageEmitter) nulls(n *storageNode, rep string, def int) {
	for col := n.column; col < n.end; col++ {
		e.g.P("columns[", col, "] = append(columns[", col, "], ", e.pq("NullValue"), "().Level(", rep, ",", def, ",", col, "))")
	}
}

func (e *storageEmitter) present(f *protogen.Field, parent string) string {
	if has, _ := f.MethodName("Has"); has != "" {
		return parent + "." + has + "()"
	}
	if f.Oneof != nil && !f.Oneof.Desc.IsSynthetic() {
		v := e.variable("has")
		e.g.P("_, ", v, " := ", parent, ".Get", f.Oneof.GoName, "().(*", e.g.QualifiedGoIdent(f.GoIdent), ")")
		return v
	}
	return "(" + parent + " != nil && " + parent + "." + f.GoName + " != nil)"
}

func (e *storageEmitter) emit(n *storageNode, expr, rep string, def, depth int) {
	switch n.kind {
	case "message", "metadata":
		for _, child := range n.children {
			value := expr
			if child.kind == "oneof" {
				v := e.variable("choice")
				e.g.P("var ", v, " int32")
				alternatives := slices.Clone(child.oneof.Fields)
				slices.SortFunc(alternatives, func(a, b *protogen.Field) int { return cmp.Compare(a.Desc.Number(), b.Desc.Number()) })
				for _, field := range alternatives {
					present := e.present(field, expr)
					e.g.P("if ", present, " { ", v, " = ", field.Desc.Number(), " }")
				}
				e.g.P("if ", v, " != 0 {")
				e.emit(child, v, rep, def+1, depth)
				e.g.P("} else {")
				e.nulls(child, rep, def)
				e.g.P("}")
				continue
			}
			if child.field != nil {
				getter, _ := child.field.MethodName("Get")
				value = expr + "." + getter + "()"
			}
			if child.optional {
				present := e.present(child.field, expr)
				e.g.P("if ", present, " {")
				e.emit(child, value, rep, def+1, depth)
				e.g.P("} else {")
				e.nulls(child, rep, def)
				e.g.P("}")
			} else {
				e.emit(child, value, rep, def, depth)
			}
		}
	case "list", "map":
		v, i, r := e.variable("values"), e.variable("i"), e.variable("rep")
		e.g.P(v, " := ", expr)
		e.g.P("if len(", v, ") == 0 {")
		e.nulls(n, rep, def)
		e.g.P("} else {")
		if n.kind == "list" {
			e.g.P("for ", i, " := range ", v, " {")
		} else {
			keys := e.variable("keys")
			e.g.P(keys, " := ", e.q("slices", "Collect"), "(", e.q("maps", "Keys"), "(", v, "))")
			if n.children[0].kind == "bool" {
				e.g.P(e.q("slices", "SortFunc"), "(", keys, ", func(a, b bool) int { if a == b { return 0 }; if a { return 1 }; return -1 })")
			} else {
				e.g.P(e.q("slices", "Sort"), "(", keys, ")")
			}
			key := e.variable("key")
			e.g.P("for ", i, ", ", key, " := range ", keys, " {")
			e.g.P(r, " := ", rep, "; if ", i, " > 0 { ", r, " = ", depth+1, " }")
			e.emit(n.children[0], key, r, def+1, depth+1)
			e.emit(n.children[1], v+"["+key+"]", r, def+1, depth+1)
			e.g.P("}}")
			return
		}
		e.g.P(r, " := ", rep, "; if ", i, " > 0 { ", r, " = ", depth+1, " }")
		e.emit(n.children[0], v+"["+i+"]", r, def+1, depth+1)
		e.g.P("}}")
	default:
		var value string
		switch n.kind {
		case "witness":
			value = e.pq("BooleanValue") + "(true)"
		case "metadata_id":
			value = e.pq("ByteArrayValue") + "([]byte(meta.MessageID))"
		case "metadata_topic":
			value = e.pq("ByteArrayValue") + "([]byte(" + strconv.Quote(e.topic) + "))"
		case "metadata_time":
			value = e.pq("Int64Value") + "(meta.ReceivedMicros)"
		case "bool":
			value = e.pq("BooleanValue") + "(" + expr + ")"
		case "int32", "sint32", "sfixed32", "enum", "oneof", "uint32", "fixed32":
			value = e.pq("Int32Value") + "(int32(" + expr + "))"
		case "int64", "sint64", "sfixed64", "uint64", "fixed64":
			value = e.pq("Int64Value") + "(int64(" + expr + "))"
		case "float":
			value = e.pq("FloatValue") + "(" + expr + ")"
		case "double":
			value = e.pq("DoubleValue") + "(" + expr + ")"
		case "string":
			value = e.pq("ByteArrayValue") + "([]byte(" + expr + "))"
		case "bytes":
			value = e.pq("ByteArrayValue") + "(" + expr + ")"
		default:
			panic("unsupported storage value " + n.kind)
		}
		e.g.P("columns[", n.column, "] = append(columns[", n.column, "], ", value, ".Level(", rep, ",", def, ",", n.column, "))")
	}
}
